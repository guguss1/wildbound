def build_basalt_column(a):
    """Three joined six-sided columns at 12, 8.6 and 5.4 studs, each leaning with a tilted, chipped top, and a
    broken piece lying beside them."""
    rng = a.rng
    rock = a.part("Rock")
    column(rock, rng, -1.0, 0.8, 2.3, 12.0, 0.32, (0.3, 0.1), chip=1.2)
    column(rock, rng, 2.1, -1.0, 2.1, 8.6, -0.34, (-0.25, 0.2), chip=0.9)
    column(rock, rng, -0.2, -3.0, 1.8, 5.4, 0.4, (0.1, -0.2), chip=0.8)
    org.rough_tube(rock, rng, [(1.6, 2.2, 0.8), (3.9, 3.4, 0.8)], [0.85, 0.7], 6, rough=0.07, flutes=0.08, floor=0.0)


def tags_basalt_column(a):
    return {"occluders": [{"name": "cluster", "center": [0.2, -0.2, 5.0], "size": [6.6, 6.6, 10.0]}]}


def build_vent(a):
    """A low cone with a notched, uneven rim, a crater floor, a chunk fallen at its foot, and a glowing throat."""
    rng = a.rng
    cone, glow = a.part("Cone"), a.part("Neon_Magma")
    sides = 10
    base = org.irregular_ring((0.0, 0.0, 0.0), U, V, 5.0, 5.0, sides, rng, wobble=0.14, jitter=0.04, phase=0.2)
    flank = [(x * 0.77 + rng.uniform(-0.12, 0.12), y * 0.77 + rng.uniform(-0.12, 0.12), 1.4) for x, y, _ in base]
    heights = (3.0, 2.9, 3.1, 2.15, 2.5, 3.0, 2.85, 3.05, 2.8, 3.0)  # a notch near the +Y side
    rim = [(x * 0.54, y * 0.54, h) for (x, y, _), h in zip(base, heights)]
    lip = [(x * 0.4 + rng.uniform(-0.05, 0.05), y * 0.4 + rng.uniform(-0.05, 0.05), h - 0.2)
           for (x, y, _), h in zip(base, heights)]
    bowl = [(x * 0.31, y * 0.31, 1.8) for x, y, _ in base]
    loft(cone, [base, flank, rim, lip, bowl], W)
    org.rock_blob(cone, rng, (4.0, -1.8, 0.0), 0.9, 0.8, 1.0, rings=2, sides=4, wobble=0.15, jitter=0.05)
    disc = org.outline_points(rng, 8, 1.35, 1.25, wobble=0.12, jitter=0.05)
    loft(glow, [[(x, y, 1.75) for x, y in disc], [(x * 0.9, y * 0.9, 2.05) for x, y in disc]], W)
    org.rock_blob(glow, rng, (0.55, 0.3, 2.0), 0.5, 0.45, 0.45, rings=2, sides=5, wobble=0.15, jitter=0.05)


def build_cool_stone(a):
    """A flat bluish slab with an uneven outline, an undercut foot, a bevelled flat top and a chipped corner."""
    rng = a.rng
    stone = a.part("Stone")
    outline = org.outline_points(rng, 10, 3.0, 2.5, wobble=0.12, jitter=0.05)
    rings = []
    for z, scale, noise in ((0.0, 0.93, 0.05), (0.55, 1.0, 0.07), (1.0, 0.9, 0.0)):
        rings.append([(x * scale * (1.0 + rng.uniform(-noise, noise)), y * scale * (1.0 + rng.uniform(-noise, noise)),
                       z) for x, y in outline])
    loft(stone, rings, W, start="cap", end=(0.0, 0.0, 1.0))


def tags_cool_stone(a):
    return {"collision_boxes": [inscribed_walk_box(a.parts["Stone"].vertices, 1.0)]}


def build_charred_tree(a):
    """A bent, narrowing burned trunk with buttressed roots, a jagged break at the top, two stubs and ember seams."""
    rng = a.rng
    wood, ember = a.part("Wood"), a.part("Neon_Magma")
    rings = []
    for z, radius in ((0.0, 2.5), (2.5, 1.95), (6.0, 1.7), (9.5, 1.45), (12.5, 1.2)):
        centre = (0.55 * math.sin(0.32 * z), 0.25 * math.sin(0.5 * z + 1.0), z)
        rings.append(org.irregular_ring(centre, U, V, radius, radius, 7, rng, wobble=0.14 if z else 0.2, jitter=0.06,
                                        phase=0.35 * len(rings)))
    top_centre = (0.55 * math.sin(0.32 * 14.8), 0.25 * math.sin(0.5 * 14.8 + 1.0))
    jag = (0.9, -0.7, 0.4, -0.9, 0.8, -0.3, 0.6)
    crown = org.irregular_ring((top_centre[0], top_centre[1], 14.8), U, V, 1.0, 1.0, 7, rng, wobble=0.1, jitter=0.05)
    rings.append([(x, y, 14.8 + j) for (x, y, _), j in zip(crown, jag)])
    loft(wood, rings, W)
    for path, radii in (([(0.6, 0.3, 8.8), (2.6, 2.6, 9.8), (4.4, 4.4, 9.4), (5.7, 5.3, 9.1)], [0.85, 0.7, 0.5, 0.0]),
                        ([(-0.4, 0.3, 6.2), (-2.4, -2.2, 7.5), (-4.2, -4.0, 7.2), (-5.6, -5.2, 6.6)],
                         [0.8, 0.65, 0.45, 0.0])):
        org.rough_tube(wood, rng, path, radii, 4, rough=0.1)
    for path in (((2.0, 0.6, 1.4), (3.4, 1.1, 0.0)), ((-1.8, 1.2, 1.5), (-3.0, 2.2, 0.0)),
                 ((0.6, -2.0, 1.5), (1.0, -3.4, 0.0))):
        org.rough_tube(wood, rng, [path[0], path[1]], [0.7, 0.0], 4, rough=0.1)
    for base, tip in (((0.3, 0.1, 14.5), (0.6, 0.2, 16.0)), ((-0.5, 0.3, 14.0), (-1.4, 0.8, 15.3))):
        org.rough_tube(wood, rng, [base, tip], [0.55, 0.0], 4, rough=0.08)
    normals = org.grid_normals(rings, (0.0, 0.0))
    org.ribbon_along(ember, rng, rings, normals, 1, 2, 1, 0.5, 0.2, lift=0.14)
    org.ribbon_along(ember, rng, rings, normals, 2, 3, 4, 0.5, 0.2, lift=0.14)


def block(part, rng, x, y, z0, z1, width, depth, taper=0.96, jitter=0.14, yaw=0.0):
    org.jittered_block(part, rng, (x, y, (z0 + z1) / 2), (width, depth, z1 - z0), jitter=jitter, taper=taper,
                       yaw=yaw + rng.uniform(-0.05, 0.05))


def build_ash_shrine(a):
    """A squat stepped gate: three tiers of hewn blocks on each side (the right one broken lower), a lintel of
    three steps, an ochre band running over both piers and the lintel, and fallen blocks."""
    rng = a.rng
    stone, trim = a.part("Stone"), a.part("Trim")
    tiers = ((0.0, 3.8, 7.6, 13.9, 6.8), (3.8, 7.6, 7.9, 12.8, 5.8), (7.6, 11.0, 8.2, 11.7, 5.0))
    for side in (-1, 1):
        for z0, z1, inner, outer, half_depth in tiers:
            if side == 1 and z0 == 7.6:
                z1 = 10.3  # the right pier is broken lower
            centre_x, width = side * (inner + outer) / 2, outer - inner
            for k in range(3):
                depth = half_depth * 2 / 3 + 0.25
                y = -half_depth + depth / 2 + k * (half_depth * 2 - depth) / 2
                block(stone, rng, centre_x + rng.uniform(-0.1, 0.1), y, z0 + 0.02 * k, z1 - 0.05 * k, width, depth)
    block(stone, rng, 9.6, 0.4, 10.2, 11.35, 3.2, 3.6, taper=0.85, jitter=0.1)  # capstone under the lintel
    for x0, x1, z0, z1, depth in ((-14.0, 0.2, 11.3, 13.3, 6.2), (-0.1, 14.0, 11.3, 13.3, 6.2),
                                  (-10.8, -0.1, 13.3, 15.1, 5.0), (-0.2, 10.8, 13.3, 15.1, 5.0)):
        block(stone, rng, (x0 + x1) / 2, rng.uniform(-0.2, 0.2), z0, z1, x1 - x0, depth * 2, taper=0.97, jitter=0.12)
    block(stone, rng, -0.4, 0.2, 15.1, 16.0, 13.0, 6.4, taper=0.9, jitter=0.1)
    for x, y, size in ((-11.8, -7.0, 1.1), (11.4, -6.9, 1.0), (-9.4, -7.1, 0.7), (12.6, 6.6, 0.9)):
        org.rock_blob(stone, rng, (x, y, 0.0), size, size * 0.9, size * 0.8, rings=2, sides=3, wobble=0.15, jitter=0.05)
    for side in (-1, 1):
        block(trim, rng, side * 10.2, -5.95, 5.15, 6.05, 5.4, 0.35, taper=1.0, jitter=0.04)
    block(trim, rng, 0.0, -6.45, 11.75, 12.65, 26.4, 0.4, taper=1.0, jitter=0.05)
    block(trim, rng, -0.3, -5.0, 13.75, 14.65, 20.6, 0.4, taper=1.0, jitter=0.05)
    block(trim, rng, -0.4, -3.35, 15.1, 15.9, 11.0, 0.4, taper=1.0, jitter=0.04)
    for x, z in ((-13.2, 5.5), (13.0, 8.6), (-13.1, 11.9)):
        org.rock_blob(trim, rng, (x, -3.6 if abs(x) < 13.2 else -2.0, z), 0.5, 0.45, 0.35, rings=2, sides=3,
                      wobble=0.1, jitter=0.04)


def tags_ash_shrine(a):
    return {"occluders": [{"name": "pier_left", "center": [-10.8, 0.0, 5.5], "size": [6.2, 13.6, 11.0]},
                          {"name": "pier_right", "center": [10.8, 0.0, 5.5], "size": [6.2, 13.6, 11.0]}]}


def build_crust_plate(a):
    """A broken crust plate: an uneven bevelled slab with a chip beside it and one glowing seam that zigzags
    across the top and stands proud of the crust."""
    rng = a.rng
    crust, seam = a.part("Crust"), a.part("Neon_Magma")
    outline = org.outline_points(rng, 12, 10.0, 10.0, wobble=0.12, jitter=0.04)
    rings = []
    for z, scale in ((0.0, 0.96), (0.28, 1.0), (0.5, 0.97)):
        rings.append([(x * scale + rng.uniform(-0.1, 0.1) * (z < 0.5), y * scale + rng.uniform(-0.1, 0.1) * (z < 0.5),
                       z) for x, y in outline])
    loft(crust, rings, W, start="cap", end=(0.0, 0.0, 0.5))
    points = ((-7.4, -3.6), (-2.6, -0.6), (2.0, -3.0), (7.2, 1.4))
    top, low = [], []
    for i, (x, y) in enumerate(points):
        ahead = points[min(i + 1, len(points) - 1)]
        behind = points[max(i - 1, 0)]
        dx, dy = ahead[0] - behind[0], ahead[1] - behind[1]
        size = math.hypot(dx, dy)
        nx, ny = -dy / size, dx / size
        half = 0.3 * rng.uniform(0.8, 1.25)
        top.append([(x + nx * half, y + ny * half, 0.54), (x - nx * half, y - ny * half, 0.54)])
        low.append([(x + nx * half, y + ny * half, 0.42), (x - nx * half, y - ny * half, 0.42)])
    org.slab_between(seam, top, low)


def tags_crust_plate(a):
    return {"collision_boxes": [inscribed_walk_box(a.parts["Crust"].vertices, 0.5)]}


def build_obsidian_shard(a):
    """Three flat glassy fins that lean away from one another at different heights, on a small ash footing."""
    rng = a.rng
    shard, base = a.part("Shard"), a.part("Base")
    org.rock_blob(base, rng, (0.0, 0.0, 0.0), 2.5, 2.45, 0.8, rings=2, sides=5, wobble=0.15, jitter=0.05, flat_top=True)
    for points, radii, angle in (([(0.2, -0.3, 0.5), (0.4, -0.8, 1.9), (0.7, -1.4, 3.2), (1.0, -1.9, 4.0)],
                                  [0.95, 1.0, 0.55, 0.0], 0.0),
                                 ([(-0.8, 0.6, 0.5), (-1.2, 0.8, 1.6), (-1.7, 1.0, 2.5), (-2.0, 1.2, 3.0)],
                                  [0.8, 0.85, 0.5, 0.0], 1.05),
                                 ([(0.9, 0.7, 0.5), (1.3, 1.0, 1.3), (1.7, 1.2, 1.9), (2.0, 1.4, 2.4)],
                                  [0.7, 0.72, 0.42, 0.0], 2.1)):
        kc.tube(shard, points, radii, 4, W, phase=0.6, squash=0.3, reference=(math.cos(angle), math.sin(angle), 0.0))


def raw_size(build, seed):
    """Measured bounding box of a prop before fitting, for props whose seams stand a little proud of the table."""
    probe = kc.Asset("probe", seed=seed)
    build(probe)
    low, high = probe.bbox()
    return tuple(h - l for l, h in zip(low, high))


def brighter_studio():
    """Dark palettes disappear in the shared studio light. Preview renders only: more key, fill and sky."""
    if bk.bpy is None:
        return
    shared = kc.add_studio

    def studio(scene, prefix="SP"):
        camera = shared(scene, prefix)
        bk.bpy.data.lights[f"{prefix}_Key"].energy = 4.0
        bk.bpy.data.lights[f"{prefix}_Fill"].energy = 1.6
        scene.world.node_tree.nodes["Background"].inputs[1].default_value = 1.5
        return camera

    kc.add_studio = studio


