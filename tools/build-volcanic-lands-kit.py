def column(part, rng, cx, cy, radius, top, tilt, lean, chip=0.8, sides=6):
    """A joined basalt column: an uneven hexagon that leans, with a sloped, chipped top. Two bands, flat base."""
    base = org.irregular_ring((cx, cy, 0.0), U, V, radius, radius, sides, rng, wobble=0.1, jitter=0.05,
                              phase=rng.uniform(0.0, 1.0))
    mid = [(x + lean[0] * 0.5 + rng.uniform(-0.06, 0.06), y + lean[1] * 0.5 + rng.uniform(-0.06, 0.06), top * 0.55)
           for x, y, _ in base]
    direction = rng.uniform(0.0, math.tau)
    dx, dy = math.cos(direction), math.sin(direction)
    crown = []
    for k, (x, y, _) in enumerate(base):
        slope = tilt * ((x - cx) * dx + (y - cy) * dy)
        crown.append((cx + (x - cx) * 0.88 + lean[0] * 0.95 + rng.uniform(-0.05, 0.05),
                      cy + (y - cy) * 0.88 + lean[1] * 0.95 + rng.uniform(-0.05, 0.05),
                      top + slope - (chip if k == 2 else 0.0) + rng.uniform(-0.05, 0.05)))
    loft(part, [base, mid, crown], W)


def inscribed_walk_box(part_vertices, height, name="walk"):
    """A square walk box inside the flat top of a slab that fans to a centre vertex at the top height.

    The fan centre is the box centre, so a vertex always sits over the walk area, and the box is measured on
    the fitted vertices (fitting shifts the slab a little, so the centre is not at the origin).
    """
    top = [v for v in part_vertices if v[2] > height - 0.01]
    mean = (sum(v[0] for v in top) / len(top), sum(v[1] for v in top) / len(top))
    centre = min(top, key=lambda v: math.dist(v[:2], mean))
    ring = [v for v in top if v is not centre]
    ring.sort(key=lambda v: math.atan2(v[1] - centre[1], v[0] - centre[0]))
    half = round(inscribed_square_half([(v[0], v[1]) for v in ring], (centre[0], centre[1])) * 0.97, 3)
    return {"name": name, "center": [round(centre[0], 4), round(centre[1], 4), round(height / 2, 4)],
            "size": [2 * half, 2 * half, height], "pitch_deg": 0.0}


