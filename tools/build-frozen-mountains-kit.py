"""Build the original Frozen Mountains prop kit (FM_) in a fresh headless Blender scene.

Run: "D:/blender/blender.exe" --background --factory-startup --python tools/build-frozen-mountains-kit.py
Set FROZEN_MOUNTAINS_KIT_MODE=verify-fbx to re-import the exports in fresh scenes instead.
Under plain Python this file does a dry run: it counts triangles, checks closure and clearance.

1 Blender unit = 1 stud. Each prop is an Empty root at the ground-level pivot with one mesh
child per material, because a Roblox MeshPart holds one colour and one material. Pine trunks
stay their own part so a Studio importer can keep them as sight blockers (bible section 1).
Snow records Yeti tracks and rock does not, so the shelf and the overhang report no-track
rectangles. All geometry is scripted here. Nothing is downloaded, generated by a service or
uploaded, and every value is unvalidated: never imported into Roblox. Spec: bible 5.1, 5.2, 5.4.
"""

