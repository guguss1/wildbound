def pine_tier(part, rng, hem_z, apex_z, radius):
    """Short skirt of twelve boughs (four long ones on the axes) closed by an apex and an underside."""
    sides, pattern = 12, (1.0, 0.78, 0.9)
    height = apex_z - hem_z
    hem, mid = [], []
    for k in range(sides):
        angle = math.tau * k / sides
        reach = radius * pattern[k % 3] * (1.0 if k % 3 == 0 else 1.0 + rng.uniform(-0.05, 0.05))
        droop = -0.3 if k % 3 == 0 else 0.35
        hem.append((reach * math.cos(angle), reach * math.sin(angle), hem_z + droop))
        mid.append((reach * 0.55 * math.cos(angle), reach * 0.55 * math.sin(angle), hem_z + height * 0.5))
    loft(part, [hem, mid], W, start=(0.0, 0.0, hem_z + 0.9), end=(0.0, 0.0, apex_z))


def snow_cap(part, hem_z, apex_z, radius):
    """Snow over the upper part of one tier; its tip stands just above the canopy apex."""
    height = apex_z - hem_z
    lower = ring_points((0.0, 0.0, hem_z + height * 0.12), U, V, radius * 0.82, radius * 0.82, 7, 0.2)
    upper = ring_points((0.0, 0.0, hem_z + height * 0.55), U, V, radius * 0.4, radius * 0.4, 7, 0.2)
    loft(part, [lower, upper], W, end=(0.0, 0.0, apex_z + 0.12))


def build_snow_pine(a):
    """Straight narrow trunk, three short tiers, snow on the tier tops."""
    rng = a.rng
    trunk, canopy, snow = a.part("Trunk"), a.part("Canopy"), a.part("Snow")
    lathe(trunk, [(1.5, 0.0), (1.05, 0.9), (0.85, 8.0), (0.7, 16.0), (0.45, 24.0)], 8, W, jitter=0.03, rng=rng)
    for hem_z, apex_z, radius in ((6.0, 15.0, 9.0), (11.0, 20.5, 6.7), (16.0, 25.7, 4.4)):
        pine_tier(canopy, rng, hem_z, apex_z, radius)
        snow_cap(snow, hem_z, apex_z, radius)


def build_ice_spire(a):
    """Leaning faceted shard with four smaller ones and a rock collar. Not glowing."""
    rng = a.rng
    ice, base = a.part("Ice"), a.part("Base")
    tube(ice, [(0.0, 0.0, 0.9), (0.55, 0.1, 5.0), (1.35, 0.2, 10.0), (2.3, 0.3, 14.0)], [1.9, 1.6, 0.95, 0.0], 8, W,
         phase=0.2)
    for angle, tip in ((0.25, 5.4), (1.85, 4.4), (2.9, 5.9), (5.85, 4.9)):
        c, s = math.cos(angle), math.sin(angle)
        tube(ice, [(c * 1.9, s * 1.9, 0.8), (c * 2.4, s * 2.4, 0.6 + tip * 0.5), (c * 2.8, s * 2.8, tip)],
             [1.0, 0.7, 0.0], 6, W, phase=rng.uniform(0.0, 1.0))
    loft(base, [ring_points((0.0, 0.0, 0.0), U, V, 3.5, 3.5, 8, 0.0),
                ring_points((0.0, 0.0, 1.7), U, V, 2.3, 2.3, 8, 0.2)], W)


def build_rock_overhang(a):
    """Slanted roof on a back wall and two side walls, open to -Y. The shelter keeps a clear 12 x 8 x 6 box."""
    rng = a.rng
    rock, snow = a.part("Rock"), a.part("Snow")
    rock_mass(rock, rng, [(-10.0, 2.7), (0.0, 2.55), (10.0, 2.7), (10.0, 6.0), (0.0, 6.0), (-10.0, 6.0)],
              ((0.0, 1.0), (4.0, 0.98), (8.0, 0.95)), 0.1)
    left = [(-10.0, -5.6), (-6.8, -5.9), (-6.6, 0.0), (-6.8, 3.2), (-10.0, 6.0), (-10.0, 0.5)]
    for outline in (left, mirrored(left)):
        rock_mass(rock, rng, outline, ((0.0, 1.0), (3.5, 0.97), (7.0, 0.9)), 0.1)
    for x in (-3.5, 3.5):  # buttresses on the back wall, kept out of the shelter box
        rock_mass(rock, rng, [(x - 2.0, 2.4), (x, 2.35), (x + 2.0, 2.45), (x + 2.0, 4.0), (x - 2.0, 4.0)],
                  ((0.0, 1.0), (3.5, 0.9), (5.5, 0.7)), 0.08)
    # Roof: two overlapping slabs with different tilts, high at the back, so it does not read as one table top.
    # Each underside is at least Z 6.2 at the front edge, above the 6-high shelter box.
    for x_low, x_high, slope, z0, thick, seed_shift in ((-10.0, 0.9, 0.06, 6.8, 1.2, 0.0), (-0.9, 10.0, 0.11, 6.9, 1.0, 0.3)):
        phi = math.atan(slope)
        v = (0.0, math.cos(phi), math.sin(phi))
        n = (0.0, -math.sin(phi), math.cos(phi))
        origin = (0.0, 0.0, z0)
        mid = (x_low + x_high) / 2
        half = (x_high - x_low) / 2
        outline = [(mid - half, -5.8 + seed_shift), (mid - half * 0.2, -6.0), (mid + half * 0.5, -5.9),
                   (mid + half, -5.5 - seed_shift), (mid + half, 0.4), (mid + half * 0.9, 5.8),
                   (mid - half * 0.2, 6.0), (mid - half, 5.7)]
        slab(rock, outline, origin, U, v, n, thick, W, bevel=0.05)
        slab(snow, [(mid + (a_ - mid) * 0.95, b * 0.94) for a_, b in outline], madd(origin, n, thick - 0.05), U, v, n,
             0.25, W)
        if x_low < 0:
            drift = add(add(madd(origin, v, -2.5), (-5.0, 0.0, 0.0)), mul(n, thick + 0.1))
        else:
            drift = add(add(madd(origin, v, -3.0), (5.5, 0.0, 0.0)), mul(n, thick + 0.1))
        lathe(snow, [(1.8, 0.0), (0.0, 0.8)], 7, W, center=drift, frame=(U, v, n), phase=rng.uniform(0, 1))


