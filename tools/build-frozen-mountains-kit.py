def rock_mass(part, rng, outline, levels, jitter=0.1):
    """A rough rock block: the outline at several heights, each scaled about its centre."""
    cx = sum(x for x, _ in outline) / len(outline)
    cy = sum(y for _, y in outline) / len(outline)
    rings = [[(cx + (x - cx) * s + rng.uniform(-jitter, jitter), cy + (y - cy) * s + rng.uniform(-jitter, jitter), z)
              for x, y in outline] for z, s in levels]
    loft(part, rings, W)


def mirrored(outline):
    return [(-x, y) for x, y in outline]


