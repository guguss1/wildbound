# Bible 5.9: size (x, y, z) in studs, and part colours. The tests hold their own copy.
SPECS = {
    "SP_Soplillo": {"size": (2.8, 3.4, 2.6),
                    "colors": {"Body": "E6EFF4", "Tail": "9CCBE0", "Neon_Eye": "4E7CC2"}},
}
CLIPS = ("Idle", "Move")


