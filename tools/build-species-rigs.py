def hex_ring(z, radius, bulge=0.0, yaw=0.0):
    """Twelve points: six corners and the bulged middle of each side."""
    points = []
    for k in range(6):
        for step, scale in ((0, 1.0), (1, math.cos(math.radians(30)) * (1.0 + bulge))):
            angle = yaw + math.radians(60 * k + 30 * step)
            points.append((math.cos(angle) * radius * scale, math.sin(angle) * radius * scale, z))
    return points


def pyramid(part, base, direction, radius, height, weigh, sides=3):
    lathe(part, [(radius, 0.0), (0.0, height)], sides, weigh, center=base, frame=kc.basis(direction))


def prism(part, base, direction, radius, height, weigh, sides=6, scale=(1.0, 1.0)):
    lathe(part, [(radius, 0.0), (radius, height)], sides, weigh, center=base, frame=kc.basis(direction),
          scale=scale)


def build_soplillo():
    asset = Asset("SP_Soplillo", seed=11)
    body, tail, eye = asset.part("Body"), asset.part("Tail"), asset.part("Neon_Eye")
    on_body = rigid("Body")

    # Six-sided puff: a hexagon with a bulged middle on each side, chamfered at both ends.
    K = 0.85
    rings = [hex_ring(z, r * K, b) for z, r, b in
             ((0.00, 0.75, 0.0), (0.12, 1.15, 0.0), (0.45, 1.38, 0.05), (0.95, 1.45, 0.08),
              (1.45, 1.40, 0.08), (1.85, 1.15, 0.05), (2.10, 0.80, 0.0), (2.18, 0.45, 0.0))]
    loft(body, rings, on_body)
    # Snow tufts: six on the shoulders pointing up and out, six low at the corners.
    for k in range(6):
        angle = math.radians(60 * k)
        out = (math.cos(angle), math.sin(angle), 0.0)
        pyramid(body, (out[0] * 0.8, out[1] * 0.8, 2.05), add(mul(out, 0.5), (0, 0, 1)), 0.3, 0.3, on_body)
        pyramid(body, (out[0] * 1.1, out[1] * 1.1, 0.35), add(mul(out, 1.0), (0, 0, 0.35)), 0.3, 0.26, on_body)

    # One long whip tail: starts behind the body and curls up, a soft hand-over at mid length.
    path = [(0, 0.9, 0.8), (0, 1.35, 0.7), (0, 1.8, 0.9), (0, 2.0, 1.4), (0, 1.9, 1.95), (0, 1.55, 2.38)]
    tube(tail, path, [0.30, 0.25, 0.20, 0.15, 0.10, 0.0], 6,
         blend("TailA", "TailB", path[0], path[-1], 0.30, 0.65), phase=0.3)
    lathe(tail, kc.arc_profile(0.22, 0.2, 2), 5, rigid("TailB"), center=(0, 1.52, 2.36))

    # Two eyes: tall hexagonal studs on the front face.
    for side in (-1, 1):
        prism(eye, (side * 0.5, -1.02, 1.2), (0, -1, 0), 0.17, 0.2, on_body, sides=6, scale=(1.0, 1.5))

    asset.bone("Root", None, (0, 0, 0), (0, 0, 0.5))
    asset.bone("Body", "Root", (0, 0, 1.05), (0, -0.7, 1.05))
    asset.bone("TailA", "Body", (0, 0.9, 0.8), (0, 1.8, 0.9))
    asset.bone("TailB", "TailA", (0, 1.8, 0.9), (0, 1.55, 2.38))
    return asset


BUILDERS = {"SP_Soplillo": build_soplillo}
ORDER = tuple(SPECS)


def author(name):
    asset = BUILDERS[name]()
    kc.fit_asset(asset, SPECS[name]["size"])
    return asset


