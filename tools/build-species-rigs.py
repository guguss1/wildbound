def is_identity(obj):
    from mathutils import Matrix
    return all(abs(a - b) < 1e-6 for row_a, row_b in zip(obj.matrix_world, Matrix.Identity(4))
               for a, b in zip(row_a, row_b))


def round_list(values, places=4):
    return [round(float(v), places) for v in values]


def measure_rest(asset, rig, meshes, depsgraph):
    """Rest-pose measurements plus the dump the spec tests recompute from."""
    parts, dump_parts, all_points, applied, flat_all = [], {}, [], is_identity(rig), True
    for obj in meshes:
        vertices, triples, open_edges, flat = kc.evaluated_triangles(obj, depsgraph)
        applied = applied and is_identity(obj)
        flat_all = flat_all and flat
        material = obj.data.materials[0]
        shader = next(n for n in material.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
        weights = []
        for vertex in obj.data.vertices:
            weights.append([[obj.vertex_groups[g.group].name, round(g.weight, 5)] for g in vertex.groups])
        dump_parts[obj.name] = {"vertices": [round_list(v) for v in vertices],
                                "triangles": [list(t) for t in triples], "weights": weights}
        all_points.extend(tuple(vertices[i] for i in t) for t in triples)
        label = obj.name[len(asset.name) + 1:]
        parts.append({
            "object": obj.name, "material": material.name, "material_count": len(obj.material_slots),
            "triangles": len(triples), "non_manifold_edges": open_edges,
            "roughness": round(shader.inputs["Roughness"].default_value, 3),
            "emission_strength": round(shader.inputs["Emission Strength"].default_value, 3),
            "color_hex": kc.linear_to_hex(shader.inputs["Base Color"].default_value),
            "default_hidden": label in asset.hidden_by_default,
        })
    points = [v for t in all_points for v in t]
    low = [min(p[i] for p in points) for i in range(3)]
    high = [max(p[i] for p in points) for i in range(3)]
    band = low[2] + (high[2] - low[2]) * 0.1
    base = [p for p in points if p[2] <= band]
    entry = {
        "status": "unvalidated",
        "triangles": len(all_points),
        "size": round_list([b - a for a, b in zip(low, high)]),
        "bbox_min": round_list(low), "bbox_max": round_list(high),
        "base_center": round_list([(min(p[i] for p in base) + max(p[i] for p in base)) / 2 for i in (0, 1)]),
        "non_manifold_edges": sum(p["non_manifold_edges"] for p in parts),
        "flat_shaded": flat_all, "transforms_applied": applied,
        "fit_scale": round_list(asset.fit),
        "bones": list(rig.data.bones.keys()),
        "parts": parts,
    }
    dump = {"bones": list(rig.data.bones.keys()),
            "rest_bones": {b.name: {"parent": b.parent.name if b.parent else None,
                                    "head": round_list(b.head_local, 5), "tail": round_list(b.tail_local, 5)}
                           for b in rig.data.bones},
            "parts": dump_parts}
    return entry, dump


def save_blend(scene):
    try:
        bpy.context.window.scene = scene
    except AttributeError:
        pass
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND), check_existing=False)


def set_visible(collections, only):
    for name, collection in collections.items():
        collection.hide_render = name != only


def render_species(collections, built, dumps):
    from mathutils import Vector
    scene = bpy.data.scenes.new("SP_Preview")
    kc.set_render_engine(scene)
    camera = kc.add_studio(scene)
    for collection in collections.values():
        scene.collection.children.link(collection)
    for name in collections:
        set_visible(collections, name)
        hidden = [o for o in built[name][2] if o.get("default_hidden")]
        for obj in hidden:
            obj.hide_render = True
        points = [Vector(v) for part in dumps[name]["parts"].values() for v in part["vertices"]]
        kc.frame_camera(camera, points, 800, 800)
        kc.render_to(scene, OUT_DIR / f"{name}.png", 800, 800)
        for obj in hidden:
            obj.hide_render = False
    for collection in collections.values():
        collection.hide_render = False
        scene.collection.children.unlink(collection)


def render_lineup(collections, report, dumps):
    from mathutils import Vector
    scene = bpy.data.scenes.new("SP_Lineup")
    kc.set_render_engine(scene)
    camera = kc.add_studio(scene)
    block, corners, half = kc.make_scale_block(scene)
    points = [Vector(c) for c in corners]
    cursor, gap = half + 1.6, 1.6
    for name in collections:
        info = report[name]
        offset = cursor - info["bbox_min"][0]
        instance = bpy.data.objects.new(f"{name}_Lineup", None)
        instance.instance_type = "COLLECTION"
        instance.instance_collection = collections[name]
        instance.location = (offset, 0.0, 0.0)
        scene.collection.objects.link(instance)
        points.extend(Vector(v) + Vector((offset, 0.0, 0.0))
                      for part in dumps[name]["parts"].values() for v in part["vertices"])
        cursor = offset + info["bbox_max"][0] + gap
    kc.frame_camera(camera, points, 2400, 800, margin=1.05)
    kc.render_to(scene, LINEUP, 2400, 800)


def build():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.name = "WildboundSpecies"
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0
    scene.render.fps = motion.FPS
    scene["studs_per_blender_unit"] = 1.0
    scene["status"] = "unvalidated: never imported into Roblox"

    assets = {name: author(name) for name in ORDER}
    materials = {}
    for name, asset in assets.items():
        for label in asset.parts:
            colour = SPECS[name]["colors"][label]
            materials[f"{name}_{label}"] = kc.make_material(
                f"{name}_{label}", colour, kc.NEON_EMISSION if label.startswith("Neon_") else 0.0)
    built = {name: kc.build_asset(asset, materials, scene) for name, asset in assets.items()}
    collections = {name: b[0] for name, b in built.items()}
    bpy.context.view_layer.update()
    depsgraph = bpy.context.evaluated_depsgraph_get()

    report, dumps, motion_dump = {}, {}, {}
    for name, asset in assets.items():
        collection, rig, meshes = built[name]
        entry, dump = measure_rest(asset, rig, meshes, depsgraph)
        entry["fbx"] = {"model": f"assets/exports/species/{name}.fbx",
                        **{clip: f"assets/exports/species/{name}_{clip}.fbx" for clip in CLIPS}}
        entry["render"] = f"assets/blender/species/{name}.png"
        report[name], dumps[name] = entry, dump
        kc.export_fbx(rig, meshes, EXPORT_DIR / f"{name}.fbx", clip=False)

        entry["clips"], motion_dump[name] = {}, {}
        for clip in CLIPS:
            action = kc.key_clip(rig, name, clip, motion)
            frames = motion.frame_count(clip)
            scene.frame_start, scene.frame_end = 1, frames
            samples = kc.sample_clip(scene, rig, meshes, action, frames)
            motion_dump[name][clip] = samples
            lowest = min(box[0][2] for boxes in samples["mesh_bbox"].values() for box in boxes)
            entry["clips"][clip] = {
                "action": action.name, "fps": motion.FPS, "frame_start": 1, "frame_end": frames,
                "duration_seconds": motion.DURATIONS[clip], "finite": samples["finite"],
                "loop_endpoint_error": kc.loop_error(samples), "lowest_z": round(lowest, 4)}
            kc.export_fbx(rig, meshes, EXPORT_DIR / f"{name}_{clip}.fbx", clip=True)
        rig.animation_data.action = None
        scene.frame_set(1)

    render_species(collections, built, dumps)
    kc.compose_sheet(list(ORDER), OUT_DIR, SHEET)
    render_lineup(collections, report, dumps)
    save_blend(scene)

    full = {
        "generator": "tools/build-species-rigs.py",
        "blender_version": bpy.app.version_string,
        "unvalidated": True,
        "studs_per_blender_unit": 1.0,
        "fbx_settings": dict(kc.FBX_SETTINGS),
        "roblox_scale_verified": False,
        "scale_note": ("Authored at 1 Blender unit = 1 stud with no rescale step. Silueta's rig once arrived "
                       "at the wrong size (docs/assets/silueta-studio-import.md:23), so scale in Roblox "
                       "stays unverified until a real import."),
        "scale_block_height": kc.SCALE_BLOCK_HEIGHT,
        "sheet_file": SHEET.name, "lineup_file": LINEUP.name,
        "blend": "assets/blender/species/species-v1.blend",
        "species": report,
    }
    kc.dump_json(REPORT, full, indent=2)
    kc.dump_json(GEOMETRY, dumps)
    kc.dump_json(MOTION_DUMP, motion_dump)
    for name in ORDER:
        e = report[name]
        print(name, e["triangles"], e["size"], "open", e["non_manifold_edges"], "fit", e["fit_scale"],
              [(p["object"][len(name) + 1:], p["triangles"]) for p in e["parts"]])


def action_curves(action):
    try:
        return [c for layer in action.layers for strip in layer.strips for bag in strip.channelbags
                for c in bag.fcurves]
    except AttributeError:
        return list(action.fcurves)


def verify_fbx():
    """Re-import every FBX in a fresh empty scene and measure what actually came back."""
    results = {}
    for name in ORDER:
        results[name] = {}
        for kind in ("model", *CLIPS):
            path = EXPORT_DIR / (f"{name}.fbx" if kind == "model" else f"{name}_{kind}.fbx")
            bpy.ops.wm.read_factory_settings(use_empty=True)
            bpy.ops.import_scene.fbx(filepath=str(path))
            bpy.context.view_layer.update()
            depsgraph = bpy.context.evaluated_depsgraph_get()
            triangles, materials, objects, bones, points = 0, set(), [], [], []
            for obj in bpy.data.objects:
                objects.append(obj.name)
                if obj.type == "ARMATURE":
                    bones.extend(b.name for b in obj.data.bones)
                if obj.type != "MESH":
                    continue
                vertices, triples, _, _ = kc.evaluated_triangles(obj, depsgraph)
                triangles += len(triples)
                points.extend(vertices[i] for t in triples for i in t)
                materials.update(m.name for m in obj.data.materials if m)
            low = [min(p[i] for p in points) for i in range(3)]
            high = [max(p[i] for p in points) for i in range(3)]
            info = {"triangles": triangles, "size": round_list([b - a for a, b in zip(low, high)]),
                    "min_z": round(low[2], 4), "bones": bones, "objects": sorted(objects),
                    "materials": sorted(materials), "actions": [a.name for a in bpy.data.actions]}
            if kind == "model":
                results[name]["model"] = info
                continue
            action = max(bpy.data.actions, key=lambda a: len(action_curves(a)))
            curves = action_curves(action)
            keyed = {round(k.co[0]) for c in curves for k in c.keyframe_points}
            start, end = action.frame_range
            fps = bpy.context.scene.render.fps
            info.update({"animated_channels": len(curves), "keyed_frames": len(keyed),
                         "frame_range": [start, end], "scene_fps": fps,
                         "duration_seconds": (end - start) / motion.FPS})
            results[name].setdefault("clips", {})[kind] = info
        print(name, results[name]["model"]["size"], results[name]["model"]["min_z"],
              {c: i["duration_seconds"] for c, i in results[name]["clips"].items()})
    kc.dump_json(ROUNDTRIP, {"species": results}, indent=2)


def dry_run():
    for name in ORDER:
        asset = BUILDERS[name]()
        low, high = asset.bbox()
        raw = [round(b - a, 2) for a, b in zip(low, high)]
        counts = {label: part.triangles for label, part in asset.parts.items()}
        kc.fit_asset(asset, SPECS[name]["size"])
        print(name, "tris", asset.triangles, counts, "raw", raw, "fit", [round(s, 3) for s in asset.fit])


if bpy is None:
    dry_run()
elif os.environ.get("SPECIES_RIGS_MODE") == "verify-fbx":
    verify_fbx()
else:
    build()
