"""Build the original Wildbound species rigs in a fresh headless Blender scene.

Run: "D:/blender/blender.exe" --background --factory-startup --python tools/build-species-rigs.py
Set SPECIES_RIGS_MODE=verify-fbx to re-import the exports in fresh scenes instead.
Under plain Python this file does a dry run: it counts triangles and prints the fit.

1 Blender unit = 1 stud. Z up, creatures face -Y. Each species is an armature plus one mesh
object per material (a Roblox MeshPart holds one colour), with two looping clips, Idle and
Move, exported as separate FBX files. All geometry is authored here. Nothing is downloaded,
generated by a service or uploaded, and every asset is labelled unvalidated.
Spec source: docs/design/wildbound-expansion-bible.md section 5.9.
"""

