def chamfer_ring(cx, cy, z, hx, hy, c, rng=None, jitter=0.0):
    """Eight points of a chamfered rectangle, counter-clockwise seen from above."""
    corners = [(cx + hx - c, cy - hy), (cx + hx, cy - hy + c), (cx + hx, cy + hy - c), (cx + hx - c, cy + hy),
               (cx - hx + c, cy + hy), (cx - hx, cy + hy - c), (cx - hx, cy - hy + c), (cx - hx + c, cy - hy)]
    out = []
    for x, y in corners:
        if jitter:
            x, y = x + rng.uniform(-jitter, jitter), y + rng.uniform(-jitter, jitter)
        out.append((x, y, z))
    return out


def bevelled_block(part, rng, weigh, cx, cy, z0, z1, hx, hy, c, cut, jitter=0.02):
    """A cube with chamfered vertical edges and chamfered top and bottom rims."""
    loft(part, [chamfer_ring(cx, cy, z0, hx - cut, hy - cut, max(c - cut * 0.5, 0.04), rng, jitter),
                chamfer_ring(cx, cy, z0 + cut, hx, hy, c, rng, jitter),
                chamfer_ring(cx, cy, z1 - cut, hx, hy, c, rng, jitter),
                chamfer_ring(cx, cy, z1, hx - cut, hy - cut, max(c - cut * 0.5, 0.04), rng, jitter)], weigh)


KITE = ((0.0, 0.0), (0.30, 0.06), (0.58, 0.28), (0.54, 0.50), (0.30, 0.76), (0.0, 1.0),
        (-0.30, 0.76), (-0.54, 0.50), (-0.58, 0.28), (-0.30, 0.06))


def petal(part, rng, weigh, base, direction, hint, length, half_width, thickness):
    """A flat cream plate that ends in a point, chamfered on its front face.

    direction runs from the base to the tip; hint is the way the plate faces.
    """
    v = unit(direction)
    u = unit(cross(v, hint))
    n = cross(u, v)
    outline = [(a * half_width * rng.uniform(0.93, 1.06), b * length * rng.uniform(0.96, 1.03)) for a, b in KITE]
    slab(part, outline, base, u, v, n, thickness, weigh, bevel=0.42)


def leaf(part, rng, weigh, path, widths, depth, fold, hint):
    """A folded mint leaf: a lengthwise ridge with the edges dropped, ending in a point.

    Each station is a four-point diamond (edge, ridge, edge, belly). Widths of zero at either
    end make that end a sharp point. hint is roughly the way the upper face looks.
    """
    frames = kc.path_frames(path, hint)
    widest = max(widths)
    rings, start, end = [], "cap", "cap"
    for index, (point, width) in enumerate(zip(path, widths)):
        if width <= 0.0:
            if index == 0:
                start = point
            else:
                end = point
            continue
        side, normal, _ = frames[index]
        ridge = depth * (0.55 + 0.45 * width / widest)
        wobble = 1.0 + rng.uniform(-0.05, 0.05)
        edge = [add(add(point, mul(side, s * width * wobble)), mul(normal, -fold * width)) for s in (1, -1)]
        rings.append([edge[0], add(point, mul(normal, ridge)), edge[1], add(point, mul(normal, -ridge * 0.45))])
    loft(part, rings, weigh, start, end)


def prism(part, base, direction, radius, height, weigh, sides=6, scale=(1.0, 1.0)):
    kc.lathe(part, [(radius, 0.0), (radius, height)], sides, weigh, center=base, frame=kc.basis(direction),
             scale=scale)


def foot(part, rng, weigh, x, y):
    """A short tapered stub, wider at the top where it meets the body, chamfered at both ends."""
    loft(part, [chamfer_ring(x, y, 0.0, 0.17, 0.18, 0.07, rng, 0.012),
                chamfer_ring(x, y, 0.24, 0.20, 0.21, 0.08, rng, 0.012),
                chamfer_ring(x, y, 0.44, 0.22, 0.23, 0.09, rng, 0.012)], weigh)


def build_lumipol():
    asset = kc.Asset(NAME, seed=611)
    rng = asset.rng
    body, petals, dark = asset.part("Body"), asset.part("Petals"), asset.part("Dark")
    leaves, eye = asset.part("Leaves"), asset.part("Neon_Eye")
    on_body, on_tuft = rigid("Body"), rigid("Tuft")

    # Beveled cream cube: the face is the -Y side.
    bevelled_block(body, rng, on_body, 0.0, 0.0, 0.36, 1.72, 0.84, 0.72, 0.22, 0.14)

    # Four small charcoal feet, front pair at -Y. L is +X.
    for name, x, y in (("FootFL", 0.52, -0.43), ("FootFR", -0.52, -0.43), ("FootBL", 0.52, 0.43),
                       ("FootBR", -0.52, 0.43)):
        foot(dark, rng, rigid(name), x, y)

    # Flat charcoal face panel standing proud of the front, with a chamfered rim.
    hw, hh, c = 0.56, 0.44, 0.2
    panel = [(hw - c, -hh), (hw, -hh + c), (hw, hh - c), (hw - c, hh), (-hw + c, hh), (-hw, hh - c),
             (-hw, -hh + c), (-hw + c, -hh)]
    slab(dark, panel, (0.0, -0.66, 1.12), (1, 0, 0), (0, 0, 1), (0, -1, 0), 0.20, on_body, bevel=0.14)

    # Two tall cyan eyes, hexagonal studs on the panel.
    for side in (-1, 1):
        prism(eye, (side * 0.28, -0.83, 1.16), (0, -1, 0), 0.10, 0.09, on_body, sides=6, scale=(0.72, 1.5))

    # Cream petals: a forelock of three that fan over the forehead, and two broad collar flaps.
    front = (0.0, -1.0, 0.12)
    petal(petals, rng, on_tuft, (0.0, -0.52, 1.58), (0.0, -0.22, 1.0), front, 0.88, 0.58, 0.15)
    petal(petals, rng, on_tuft, (0.42, -0.56, 1.56), (0.78, -0.22, 0.70), (0.3, -1.0, 0.1), 0.76, 0.50, 0.14)
    petal(petals, rng, on_tuft, (-0.42, -0.56, 1.56), (-0.78, -0.22, 0.70), (-0.3, -1.0, 0.1), 0.76, 0.50, 0.14)
    petal(petals, rng, on_body, (0.66, -0.52, 1.46), (0.40, -0.28, -0.86), (0.75, -0.7, 0.25), 1.0, 0.64, 0.17)
    petal(petals, rng, on_body, (-0.66, -0.52, 1.46), (-0.40, -0.28, -0.86), (-0.75, -0.7, 0.25), 1.0, 0.64, 0.17)

    # Two mint ears, one broad and angled, one upright, and a short leaf tail.
    leaf(leaves, rng, rigid("LeafL"),
         [(-0.36, 0.06, 1.62), (-0.58, 0.08, 1.78), (-0.85, 0.11, 1.92), (-1.10, 0.14, 1.95), (-1.30, 0.15, 1.84),
          (-1.42, 0.15, 1.70)],
         [0.10, 0.26, 0.34, 0.30, 0.17, 0.0], 0.09, 0.30, (0.0, -0.35, 1.0))
    leaf(leaves, rng, rigid("LeafR"),
         [(0.34, 0.08, 1.62), (0.36, 0.11, 1.86), (0.42, 0.13, 2.12), (0.50, 0.12, 2.36), (0.61, 0.10, 2.56),
          (0.70, 0.08, 2.72)],
         [0.10, 0.25, 0.32, 0.29, 0.16, 0.0], 0.09, 0.30, (-0.2, -1.0, 0.1))
    leaf(leaves, rng, blend("Body", "Tail", (0, 0.58, 1.0), (0, 1.05, 1.18), 0.1, 0.9),
         [(0.0, 0.55, 1.00), (0.0, 0.76, 1.08), (0.0, 1.00, 1.18), (0.0, 1.24, 1.27), (0.0, 1.42, 1.30)],
         [0.12, 0.23, 0.25, 0.15, 0.0], 0.07, 0.30, (0.0, -0.2, 1.0))

    asset.bone("Root", None, (0, 0, 0), (0, 0, 0.4))
    asset.bone("Body", "Root", (0, 0, 0.95), (0, -0.6, 0.95))
    asset.bone("Tuft", "Body", (0, -0.50, 1.60), (0, -0.64, 2.50))
    asset.bone("LeafL", "Body", (-0.38, 0.06, 1.62), (-1.74, 0.15, 1.70))
    asset.bone("LeafR", "Body", (0.34, 0.08, 1.62), (0.78, 0.08, 2.96))
    asset.bone("Tail", "Body", (0.0, 0.55, 1.0), (0.0, 1.42, 1.30))
    for name, x, y in (("FootFL", 0.52, -0.43), ("FootFR", -0.52, -0.43), ("FootBL", 0.52, 0.43),
                       ("FootBR", -0.52, 0.43)):
        asset.bone(name, "Body", (x, y, 0.40), (x, y, 0.04))
    return asset


def pin_root(asset):
    """Slide the fitted asset so the Root bone head is exactly at X 0, Y 0 (the one unified pivot).

    fit_asset centres the base band, which leaves the Root a few thousandths off the origin.
    """
    root = next(b for b in asset.bones if b[0] == "Root")
    dx, dy = root[2][0], root[2][1]
    for part in asset.parts.values():
        part.vertices = [(v[0] - dx, v[1] - dy, v[2]) for v in part.vertices]
    asset.bones = [(n, p, (h[0] - dx, h[1] - dy, h[2]), (t[0] - dx, t[1] - dy, t[2]))
                   for n, p, h, t in asset.bones]


def author():
    asset = build_lumipol()
    kc.fit_asset(asset, SPEC["size"])
    pin_root(asset)
    return asset


