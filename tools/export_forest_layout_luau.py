"""Emit the Studio ModuleScript source for the forest layout plan.

The plan JSON stays the single source of truth. This tool only reformats it:

    python -I -B tools/export_forest_layout_luau.py            # writes the module to stdout
    python -I -B tools/export_forest_layout_luau.py --adler32  # prints the module's Adler-32

Paste the output into `ServerStorage.WildboundForestLayout` and compare the Adler-32 with the one
computed over the script's Source in Studio, so a transcription slip cannot go unnoticed.
"""
import argparse
import json
import sys
import zlib
from pathlib import Path

PLAN = Path(__file__).resolve().parent.parent / "assets" / "maps" / "forest-layout" / "forest-layout-v1.json"
EXTRA_KEYS = ("totals", "inputs", "nest_cover")
ROW_FIELDS = ("id", "name", "x", "z", "rotation_y_deg", "scale", "zone")


def render(plan: dict) -> str:
    rows = "\n".join("|".join(str(item[field]) for field in ROW_FIELDS) for item in plan["instances"])
    extra = json.dumps({key: plan[key] for key in EXTRA_KEYS}, separators=(",", ":"), sort_keys=True)
    for text in (rows, extra):
        if "]==]" in text:
            raise ValueError("plan text would close the Luau long string")
    return f"""-- GENERATED by tools/export_forest_layout_luau.py from {PLAN.name}. Do not edit by hand.
-- Returns the plan's `instances` array: {{ id, name, x, z, rotation_y_deg, scale, zone }}.
-- The array also carries the plan's `totals`, `inputs` and `nest_cover` tables as named fields,
-- so the tests read every layout fact from this one module.
local HttpService = game:GetService('HttpService')

local ROWS = [==[
{rows}
]==]

local EXTRA = [==[{extra}]==]

local instances = {{}}
for line in string.gmatch(ROWS, '[^\\n]+') do
    local id, name, x, z, rotation, scale, zone =
        string.match(line, '^([^|]+)|([^|]+)|([^|]+)|([^|]+)|([^|]+)|([^|]+)|([^|]+)$')
    assert(id, 'malformed layout row: ' .. line)
    table.insert(instances, {{
        id = id, name = name, x = tonumber(x), z = tonumber(z),
        rotation_y_deg = tonumber(rotation), scale = tonumber(scale), zone = zone,
    }})
end

for key, value in pairs(HttpService:JSONDecode(EXTRA)) do
    instances[key] = value
end
return instances
"""


def adler32(text: str) -> int:
    return zlib.adler32(text.encode("utf-8")) & 0xFFFFFFFF


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--adler32", action="store_true", help="print only the Adler-32 of the module")
    args = parser.parse_args(argv)
    module = render(json.loads(PLAN.read_text(encoding="utf-8")))
    if args.adler32:
        print(adler32(module))
    else:
        sys.stdout.buffer.write(module.encode("utf-8"))  # bytes: keep LF on Windows
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
