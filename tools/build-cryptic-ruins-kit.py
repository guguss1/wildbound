def raw_size(build, seed):
    """Measured bounding box of a prop before fitting. The archway and colonnade carry fallen blocks and
    plates just past the table's size, inside its 10% tolerance; fitting to the table would squeeze the gap."""
    probe = kc.Asset("probe", seed=seed)
    build(probe)
    low, high = probe.bbox()
    return tuple(h - l for l, h in zip(low, high))


