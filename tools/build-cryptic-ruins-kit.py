def build_broken_wall(a):
    """Three courses of separate blocks laid with offset joints, then a stepped broken top, a loose block and moss."""
    rng = a.rng
    CLAMP[0] = (6.95, 1.55)
    stone, moss = a.part("Stone"), a.part("Moss")
    courses = ((0.0, 2.2, (3.5, 3.4, 3.7, 3.4)), (2.2, 4.4, (2.4, 3.9, 3.5, 4.2)), (4.4, 6.6, (3.8, 3.2, 3.3, 3.7)))
    for z0, z1, widths in courses:
        x = -7.0
        for width in widths:
            block(stone, rng, x + width / 2, rng.uniform(-0.15, 0.15), z0, z1, width - 0.06, 2.5, taper=0.97, jitter=0.1)
            x += width
    for x0, x1, top in ((-7.0, -3.4, 9.4), (-3.4, 0.2, 7.5), (0.2, 3.6, 8.3)):
        block(stone, rng, (x0 + x1) / 2, rng.uniform(-0.1, 0.1), 6.5, top, x1 - x0 - 0.1, 2.35, taper=0.85, jitter=0.1)
    block(stone, rng, 5.3, 0.1, 6.5, 6.95, 2.2, 2.4, taper=0.8, jitter=0.08, yaw=0.15)
    for x, y, z in ((-5.2, 0.0, 9.4), (1.8, 0.0, 8.3), (5.3, 0.1, 6.95)):
        org.rock_blob(moss, rng, (x, y, z - 0.15), 0.9, 0.8, 0.5, rings=2, sides=4, wobble=0.15, jitter=0.05,
                      flat_top=True)


