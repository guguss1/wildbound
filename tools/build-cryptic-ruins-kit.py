def raw_size(build, seed):
    """Measured bounding box of a prop before fitting. The archway and colonnade carry fallen blocks and
    plates just past the table's size, inside its 10% tolerance; fitting to the table would squeeze the gap."""
    probe = kc.Asset("probe", seed=seed)
    build(probe)
    low, high = probe.bbox()
    return tuple(h - l for l, h in zip(low, high))


def brighter_studio():
    """Preview renders only: more key, fill and sky than the shared studio, so violet and slate read."""
    if bk.bpy is None:
        return
    shared = kc.add_studio

    def studio(scene, prefix="SP"):
        camera = shared(scene, prefix)
        bk.bpy.data.lights[f"{prefix}_Key"].energy = 3.6
        bk.bpy.data.lights[f"{prefix}_Fill"].energy = 1.2
        scene.world.node_tree.nodes["Background"].inputs[1].default_value = 1.2
        return camera

    kc.add_studio = studio


