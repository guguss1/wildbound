def build_colonnade(a):
    """Three square columns of stacked drums that drift off line, the last one broken short, with a cracked,
    uneven beam on top, trim bands and rubble at the foot."""
    rng = a.rng
    stone, trim = a.part("Stone"), a.part("Trim")
    for cx, top, drift in ((-10.3, 10.9, 0.05), (0.0, 10.9, -0.06), (10.3, 9.5, 0.07)):
        block(stone, rng, cx, 0.0, 0.0, 0.9, 3.7, 4.4)
        shaft = top - 0.9 - 0.9
        for i in range(4):
            z0 = 0.9 + shaft * i / 4
            block(stone, rng, cx + drift * i * 2 + rng.uniform(-0.1, 0.1), rng.uniform(-0.1, 0.1), z0 - 0.02,
                  z0 + shaft / 4, 3.3 - 0.1 * i, 3.6 - 0.08 * i, taper=0.95, jitter=0.1, yaw=0.07 * (-1) ** i)
        if top > 10.0:
            block(stone, rng, cx, 0.0, top - 0.9, top, 3.8, 4.4, taper=0.92)
        else:
            block(stone, rng, cx + 0.2, 0.2, top - 0.9, 10.7, 3.0, 3.6, taper=0.78)  # a fallen capital wedged under the beam
    block(stone, rng, -5.7, 0.0, 10.9, 12.7, 13.6, 4.4, taper=0.98, jitter=0.1)
    block(stone, rng, -5.8, 0.1, 12.7, 13.9, 7.4, 3.6, taper=0.9, jitter=0.1)
    block(stone, rng, 7.0, 0.0, 10.7, 12.3, 10.2, 4.4, taper=0.98, jitter=0.1)
    block(stone, rng, 7.6, 0.2, 12.3, 13.1, 3.8, 3.2, taper=0.85, jitter=0.1)
    for x, y, w, d, h in ((-11.6, 1.5, 1.0, 0.9, 0.7), (-9.7, -1.4, 0.9, 0.9, 0.6), (0.9, 1.6, 0.9, 0.9, 0.6),
                          (11.4, -1.3, 1.0, 1.0, 0.7), (9.4, 1.5, 0.9, 0.9, 0.5)):
        block(stone, rng, x, y, 0.0, h, w, d, taper=0.85, jitter=0.1, yaw=rng.uniform(0.0, 1.0))
    for cx in (-10.3, 0.0):
        plate(trim, rng, cx, -2.3, 10.45, 3.85, 0.3, 0.5)
    plate(trim, rng, 10.3, -2.3, 10.2, 3.85, 0.3, 0.5)
    plate(trim, rng, -5.5, -2.35, 11.8, 13.0, 0.3, 0.5)
    plate(trim, rng, 6.8, -2.35, 11.5, 10.0, 0.3, 0.5)


def tags_colonnade(a):
    return {"occluders": [box_record(f"column_{i}", (cx, 0.0, 5.5), (3.9, 4.6, 11.0))
                          for i, cx in enumerate((-10.3, 0.0, 10.3))]}


def build_broken_wall(a):
    """Three courses of separate blocks laid with offset joints, then a stepped broken top, a loose block and moss."""
    rng = a.rng
    stone, moss = a.part("Stone"), a.part("Moss")
    courses = ((0.0, 2.2, (3.5, 3.4, 3.7, 3.4)), (2.2, 4.4, (2.4, 3.9, 3.5, 4.2)), (4.4, 6.6, (3.8, 3.2, 3.3, 3.7)))
    for z0, z1, widths in courses:
        x = -7.0
        for width in widths:
            block(stone, rng, x + width / 2, rng.uniform(-0.15, 0.15), z0, z1, width - 0.06, 2.8, taper=0.97, jitter=0.1)
            x += width
    for x0, x1, top in ((-7.0, -3.4, 9.4), (-3.4, 0.2, 7.5), (0.2, 3.6, 8.3)):
        block(stone, rng, (x0 + x1) / 2, rng.uniform(-0.1, 0.1), 6.5, top, x1 - x0 - 0.1, 2.6, taper=0.85, jitter=0.1)
    block(stone, rng, 5.3, 0.1, 6.5, 6.95, 2.2, 2.4, taper=0.8, jitter=0.08, yaw=0.15)
    for x, y, z in ((-5.2, 0.0, 9.4), (1.8, 0.0, 8.3), (5.3, 0.1, 6.95)):
        org.rock_blob(moss, rng, (x, y, z - 0.15), 0.9, 0.8, 0.5, rings=2, sides=4, wobble=0.15, jitter=0.05,
                      flat_top=True)


def tags_broken_wall(a):
    return {"occluders": [box_record("wall", (0.0, 0.0, 3.5), (14.3, 3.0, 7.0))]}


def build_plinth(a):
    """A two-tier square step with a flat rim, a shallow pocket and an inset glowing glyph plate."""
    rng = a.rng
    stone, glyph = a.part("Stone"), a.part("Neon_Glyph")
    block(stone, rng, 0.0, 0.0, 0.0, 1.0, 6.0, 6.0, taper=0.95, jitter=0.08)
    block(stone, rng, 0.0, 0.0, 1.0, 1.8, 5.3, 5.3, taper=0.96, jitter=0.06)
    square_frame(stone, rng, 2.0, 2.0, 0.45, 1.8, 2.0)
    block(stone, rng, 2.55, 2.5, 1.0, 1.5, 0.7, 0.7, taper=0.8, jitter=0.06)
    shape = ((-1.1, -1.0), (0.2, -1.0), (0.2, -0.2), (1.1, -0.2), (1.1, 0.6), (-0.2, 0.6), (-0.2, 1.1), (-1.1, 1.1))
    loft(glyph, [[(x, y, 1.82) for x, y in shape], [(x, y, 1.93) for x, y in shape]], W)


def tags_plinth(a):
    return {"tiny": True, "collision_boxes": [{"name": "walk", "center": [0.0, 0.0, 1.0], "size": [5.0, 5.0, 2.0],
                                               "pitch_deg": 0.0}]}


def build_archway(a):
    """A flat-lintel gate on thick stepped piers: stacked drums, a bridge block under the lintel, a three-step
    lintel, violet bands and fallen blocks."""
    rng = a.rng
    stone, trim = a.part("Stone"), a.part("Trim")
    for side, inner_top, outer_top in ((-1, 11.2, 8.4), (1, 10.5, 7.1)):
        for x0, x1, top, depth, drums in ((7.6, 10.6, inner_top, 7.0, 4), (10.6, 14.0, outer_top, 6.6, 3)):
            step = top / drums
            for i in range(drums):
                block(stone, rng, side * (x0 + x1) / 2 + rng.uniform(-0.08, 0.08), rng.uniform(-0.12, 0.12),
                      step * i - (0.02 if i else 0.0), step * (i + 1), x1 - x0 - 0.1 * i, depth - 0.12 * i,
                      taper=0.95, jitter=0.1, yaw=0.05 * (-1) ** (i + (side > 0)))
    block(stone, rng, 9.0, 0.0, 10.5, 11.5, 2.6, 5.4, taper=0.8)
    for x0, x1 in ((-14.0, -4.6), (-4.7, 4.8), (4.7, 14.0)):
        block(stone, rng, (x0 + x1) / 2, rng.uniform(-0.1, 0.1), 11.4, 14.0, x1 - x0, 7.6, taper=0.97, jitter=0.1)
    for x0, x1 in ((-9.8, 0.2), (0.1, 9.8)):
        block(stone, rng, (x0 + x1) / 2, rng.uniform(-0.1, 0.1), 14.0, 16.3, x1 - x0, 6.0, taper=0.95, jitter=0.1)
    block(stone, rng, -0.1, 0.0, 16.3, 18.0, 10.2, 5.0, taper=0.88, jitter=0.1)
    for x, y, w, d, h in ((-11.4, -3.3, 1.5, 1.2, 0.8), (11.0, 3.2, 1.4, 1.3, 0.7), (-9.0, -3.4, 1.0, 1.0, 0.5),
                          (12.3, -3.3, 1.2, 1.1, 0.6)):
        block(stone, rng, x, y, 0.0, h, w, d, taper=0.85, jitter=0.08, yaw=rng.uniform(0.0, 1.0))
    for x, w in ((-9.3, 8.8), (0.1, 9.6), (9.4, 8.9)):
        plate(trim, rng, x, -3.95, 12.4, w, 0.3, 0.8)
    plate(trim, rng, 0.0, -3.15, 14.8, 18.6, 0.3, 0.8)
    plate(trim, rng, 0.0, -2.65, 17.0, 9.0, 0.3, 0.8)
    for side in (-1, 1):
        plate(trim, rng, side * 9.1, -3.6, 5.4, 2.8, 0.3, 0.8)
    plate(trim, rng, 0.0, 3.95, 12.4, 26.0, 0.3, 0.8)


def tags_archway(a):
    return {"occluders": [box_record("pier_left", (-10.8, 0.0, 5.5), (6.4, 6.8, 11.0)),
                          box_record("pier_right", (10.8, 0.0, 5.5), (6.4, 6.8, 11.0))]}


def build_reliquary(a):
    """A waist-high chest: a wider plinth, a straight-sided body, four corner posts, a rim round a shallow recess
    and violet panels on the front."""
    rng = a.rng
    stone, trim = a.part("Stone"), a.part("Trim")
    block(stone, rng, 0.0, 0.0, 0.0, 0.7, 8.0, 4.0, taper=0.97, jitter=0.07)
    block(stone, rng, 0.0, 0.0, 0.7, 3.2, 6.9, 3.2, taper=0.99, jitter=0.06)
    for (sx, sy), top in (((-1, -1), 3.0), ((-1, 1), 3.8), ((1, -1), 3.6), ((1, 1), 2.7)):  # one post is broken short
        block(stone, rng, sx * 3.3, sy * 1.35, 0.7, top, 0.9, 0.9, taper=0.9, jitter=0.05)
    square_frame(stone, rng, 2.9, 1.1, 0.35, 3.2, 4.0)
    block(stone, rng, -2.0, 0.1, 3.2, 3.9, 1.5, 1.5, taper=0.8, jitter=0.05, yaw=0.5)  # a lid fragment in the recess
    for x in (-1.9, 1.9):
        plate(trim, rng, x, -1.62, 1.95, 2.6, 0.2, 1.3)
    plate(trim, rng, 3.5, 0.0, 1.95, 0.2, 2.4, 1.3)
    plate(trim, rng, -3.5, 0.0, 1.95, 0.2, 2.4, 1.3)


def build_glyph_stone(a):
    """A leaning, narrowing standing stone with two small stones at its foot and a thin raised plate on -Y."""
    rng = a.rng
    stone, glyph = a.part("Stone"), a.part("Neon_Glyph")
    levels = ((0.0, 1.95, 1.45), (1.8, 1.75, 1.35), (3.6, 1.45, 1.1), (4.7, 1.0, 0.78))
    rings = [org.irregular_ring((0.14 * z, 0.04 * z, z), U, V, rx, ry, 6, rng, wobble=0.1, jitter=0.05,
                                phase=0.3 + 0.25 * i) for i, (z, rx, ry) in enumerate(levels)]
    loft(stone, rings, W)
    block(stone, rng, 1.2, -0.7, 0.0, 0.45, 0.8, 0.7, taper=0.8, jitter=0.05)
    block(stone, rng, -1.1, 0.8, 0.0, 0.35, 0.7, 0.6, taper=0.8, jitter=0.05)
    face = min(v[1] for v in rings[1] + rings[2]) + 0.1
    shape = ((-0.55, 2.0), (0.05, 1.75), (0.6, 2.0), (0.7, 2.8), (0.3, 3.3), (-0.2, 3.3), (-0.65, 2.9), (-0.7, 2.4))
    centre_x = 0.14 * 2.6
    loft(glyph, [[(centre_x + x, face - 0.17, z) for x, z in shape], [(centre_x + x, face + 0.1, z) for x, z in shape]], W)


def build_stair_run(a):
    """Six solid steps of two studs run and one stud rise, each a little uneven, flanked by two broken walls."""
    rng = a.rng
    stone = a.part("Stone")
    for k in range(1, 7):
        if k == 6:  # the top tread is two blocks, so a vertex stands in the middle of the landing
            for y in (-6.0 + 2.0 * 5.0 + 0.5, -6.0 + 2.0 * 5.0 + 1.5):
                block(stone, rng, rng.uniform(-0.05, 0.05), y, 0.0, 6.0, 13.8, 1.05, taper=0.995, jitter=0.18)
            continue
        block(stone, rng, rng.uniform(-0.05, 0.05), -6.0 + 2.0 * (k - 0.5), 0.0, float(k), 13.8, 2.05, taper=0.995,
              jitter=0.18, yaw=0.0)
    for side in (-1, 1):
        x0, x1 = (7.2, 8.0) if side > 0 else (-8.0, -7.2)
        low, high = 1.5 + rng.uniform(0.0, 0.5), 5.9 - rng.uniform(0.0, 0.8)
        corners = [(x0, -5.9, 0.0), (x1, -5.9, 0.0), (x1, 5.9, 0.0), (x0, 5.9, 0.0),
                   (x0, -5.9, low), (x1, -5.9, low + 0.3), (x1, 5.9, high), (x0, 5.9, high - 0.4)]
        kc.hexahedron(stone, [(x + rng.uniform(-0.06, 0.06), y + rng.uniform(-0.06, 0.06), z + (rng.uniform(0.0, 0.12)
                                                                                                    if z else 0.0))
                              for x, y, z in corners], W)


