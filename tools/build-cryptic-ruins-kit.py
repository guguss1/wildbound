"""Build the original Cryptic Ruins prop kit (CR_) in a fresh headless Blender scene.

Run: "D:/blender/blender.exe" --background --factory-startup --python tools/build-cryptic-ruins-kit.py
Set CRYPTIC_RUINS_KIT_MODE=verify-fbx to re-import the exports in fresh scenes instead.
Under plain Python this file does a dry run: it counts triangles, checks closure and clearance.

1 Blender unit = 1 stud. Each prop is an Empty root at the ground-level pivot with one mesh
child per material, because a Roblox MeshPart holds one colour and one material. Glowing glyph
plates are their own mesh, labelled Neon_Glyph. Walls and columns declare occluder boxes, because
decorative meshes do not block the server's sight rays (bible section 1). All geometry is scripted
here. Nothing is downloaded, generated by a service or uploaded, and every value is unvalidated:
never imported into Roblox. Spec: bible 5.1, 5.2, 5.7.
"""

