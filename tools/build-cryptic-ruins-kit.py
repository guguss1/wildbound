def block(part, rng, x, y, z0, z1, width, depth, taper=0.97, jitter=0.12, yaw=0.0, lean=None, chip=None,
          worn=True, clamp=None):
    """A hewn stone, weathered: moved corners, a taper, a small turn, a lean that carries the top off the base and
    (often) one top corner knocked off. worn=False gives the plain jittered block that walk surfaces and the
    archway's measured passage rely on.

    Both modes draw exactly what the plain block drew from the prop's rng (one turn, 24 corner values), and the
    worn block takes its own randomness from one of those values, so a prop's plain blocks, plates and rubble stay
    exactly where they were. clamp is (half_x, half_y): worn corners never pass it, which keeps the extents the
    layout plan measured."""
    turn_jitter = rng.uniform(-0.05, 0.05)
    if not worn:
        org.jittered_block(part, rng, (x, y, (z0 + z1) / 2), (width, depth, z1 - z0), jitter=jitter, taper=taper,
                           yaw=yaw + turn_jitter)
        return
    clamp = clamp or CLAMP[0]
    local = random.Random(rng.random())
    for _ in range(23):
        rng.random()
    height = z1 - z0
    jitter *= 1.35
    if lean is None:
        lean = (local.uniform(-0.09, 0.09) * height, local.uniform(-0.09, 0.09) * height)
    if chip is None:
        chip = local.uniform(0.15, 0.45) * min(height, 1.4) if local.random() < 0.6 else 0.0
    knocked = local.randrange(4)
    turn = yaw + turn_jitter + local.uniform(-0.04, 0.04)
    cos_y, sin_y = math.cos(turn), math.sin(turn)
    sx, sy = width / 2, depth / 2

    def corner(index, px, py, top):
        scale = taper if top else 1.0
        qx, qy = px * scale, py * scale
        z = z1 + local.uniform(-jitter, jitter) * 0.6 if top else z0 + local.uniform(-jitter, jitter) * 0.25
        dx, dy = lean if top else (0.0, 0.0)
        if top and chip and index == knocked:
            qx, qy, z = qx * 0.78, qy * 0.78, z - chip
        cx = x + qx * cos_y - qy * sin_y + dx + local.uniform(-jitter, jitter)
        cy = y + qx * sin_y + qy * cos_y + dy + local.uniform(-jitter, jitter)
        if clamp:
            cx, cy = max(-clamp[0], min(clamp[0], cx)), max(-clamp[1], min(clamp[1], cy))
        return (cx, cy, z)

    ring = [(-sx, -sy), (sx, -sy), (sx, sy), (-sx, sy)]
    kc.hexahedron(part, [corner(i, px, py, False) for i, (px, py) in enumerate(ring)]
                  + [corner(i, px, py, True) for i, (px, py) in enumerate(ring)], W)


def plate(part, rng, x, y, z, width, depth, height):
    """A thin trim plate laid on a face, nearly square-cut."""
    org.jittered_block(part, rng, (x, y, z), (width, depth, height), jitter=0.03, taper=1.0)


def square_frame(part, rng, half_x, half_y, half_width, z0, z1, jitter=0.04):
    """A closed rectangular frame (four mitred corner stations), a flat-topped ring of stone."""
    rings = []
    for sx, sy in ((1, 1), (-1, 1), (-1, -1), (1, -1)):
        rings.append([(sx * (half_x - half_width) + rng.uniform(-jitter, jitter),
                       sy * (half_y - half_width) + rng.uniform(-jitter, jitter), z0),
                      (sx * (half_x + half_width), sy * (half_y + half_width), z0),
                      (sx * (half_x + half_width), sy * (half_y + half_width), z1 + rng.uniform(-jitter, jitter)),
                      (sx * (half_x - half_width) + rng.uniform(-jitter, jitter),
                       sy * (half_y - half_width) + rng.uniform(-jitter, jitter), z1 + rng.uniform(-jitter, jitter))])
    kc.loft_closed(part, [ring[::-1] for ring in rings], W)  # reversed: faces point outward


def box_record(name, centre, size):
    return {"name": name, "center": [round(c, 4) for c in centre], "size": [round(s, 4) for s in size]}


