def wedge(part, base, apex, along, length, centre_z, rng):
    """A raised strap or plate: a triangular prism whose base lies on a face and whose ridge stands off it.
    base and apex are (lateral, depth) pairs; the prism runs `length` along the Z axis (along=True) or Y."""
    rings = []
    for z in (centre_z - length / 2, centre_z + length / 2):
        z += rng.uniform(-0.04, 0.04)
        rings.append([(base[0][0], base[0][1], z), (base[1][0], base[1][1], z), (apex[0], apex[1], z)])
    (ax, ay, _), (bx, by, _), (cx, cy, _) = rings[0]
    if (bx - ax) * (cy - ay) - (by - ay) * (cx - ax) < 0.0:  # a counter-clockwise base keeps the faces outward
        rings = [ring[::-1] for ring in rings]
    kc.loft(part, rings, W)


def build_reliquary(a):
    """A strapped stone chest, not a coffin: a wide plinth, a square body with violet straps and a lock plate, three
    corner posts (the fourth has fallen), a rim round a shallow recess on the left half and, on the right half, the
    lid pushed askew: a domed slab with a crown. Stone is exactly 116 triangles and trim 48, so the layout plan's
    measured 164 stays true."""
    rng = a.rng
    CLAMP[0] = None
    stone, trim = a.part("Stone"), a.part("Trim")
    block(stone, rng, 0.0, 0.0, 0.0, 0.7, 8.0, 4.0, taper=0.97, jitter=0.07, chip=0.35)
    block(stone, rng, 0.0, 0.0, 0.7, 3.2, 6.9, 3.2, taper=0.99, jitter=0.06, lean=(0.0, 0.0), chip=0.0)
    for (sx, sy), top in (((-1, -1), 3.0), ((-1, 1), 3.8), ((1, -1), 3.6)):  # one post is broken short
        block(stone, rng, sx * 3.3, sy * 1.35, 0.7, top, 0.9, 0.9, taper=0.9, jitter=0.05, chip=0.25)
    # The rim stands round the open half only; the right half carries the lid.
    rings = []
    left, right, half_y, width = -3.1, 0.55, 1.15, 0.38
    for cx, cy, fx, fy in ((right, half_y, -1, -1), (left, half_y, 1, -1), (left, -half_y, 1, 1), (right, -half_y, -1, 1)):
        j = lambda: rng.uniform(-0.05, 0.05)  # noqa: E731
        z1 = 3.2 + 0.7 + rng.uniform(-0.1, 0.1)
        rings.append([(cx + fx * width + j(), cy + fy * width + j(), 3.2), (cx + j(), cy + j(), 3.2),
                      (cx + j(), cy + j(), z1), (cx + fx * width + j(), cy + fy * width + j(), z1 + j())])
    kc.loft_closed(stone, [ring[::-1] for ring in rings], W)  # reversed: faces point outward
    # The lid: a domed slab over the right half, turned a little and pushed off the rim.
    yaw = -0.13
    cos_y, sin_y = math.cos(yaw), math.sin(yaw)
    section = ((-1.5, 3.15), (-1.5, 3.4), (-0.75, 3.87), (0.75, 3.87), (1.5, 3.4), (1.5, 3.15))
    lid = []
    for x, swell in ((1.7, 0.92), (3.8, 1.0)):
        lid.append([(2.75 + (x - 2.75) * cos_y - lateral * swell * sin_y + rng.uniform(-0.06, 0.06),
                     0.18 + (x - 2.75) * sin_y + lateral * swell * cos_y + rng.uniform(-0.06, 0.06), z)
                    for lateral, z in section])
    kc.loft(stone, [ring[::-1] for ring in lid], W)
    # A chip of the lid lies in the recess: a four-sided splinter.
    kc.loft(stone, [[(-2.3, 0.3, 3.2), (-1.5, -0.1, 3.2), (-1.9, 0.6, 3.2)]], W, end=(-1.9, 0.2, 3.65))
    # Violet straps run up the front and the two ends; a small plate marks the lock.
    for x in (-2.5, -0.1, 2.5):
        wedge(trim, ((x - 0.42, -1.46), (x + 0.42, -1.46)), (x + rng.uniform(-0.05, 0.05), -1.86), True, 2.2, 1.95, rng)
    for side in (-1, 1):
        wedge(trim, ((side * 3.35, -0.3), (side * 3.35, 0.3)), (side * 3.62, 0.0), True, 2.0, 1.95, rng)
    wedge(trim, ((-0.4, -1.5), (0.4, -1.5)), (0.0, -1.95), True, 0.7, 2.7, rng)


def build_glyph_stone(a):
    """A leaning, narrowing standing stone with two small stones at its foot and a thin raised plate on -Y."""
    rng = a.rng
    stone, glyph = a.part("Stone"), a.part("Neon_Glyph")
    levels = ((0.0, 1.95, 1.45), (1.8, 1.75, 1.35), (3.6, 1.45, 1.1), (4.7, 1.0, 0.78))
    rings = [org.irregular_ring((0.14 * z, 0.04 * z, z), U, V, rx, ry, 6, rng, wobble=0.1, jitter=0.05,
                                phase=0.3 + 0.25 * i) for i, (z, rx, ry) in enumerate(levels)]
    loft(stone, rings, W)
    block(stone, rng, 1.2, -0.7, 0.0, 0.45, 0.8, 0.7, taper=0.8, jitter=0.05)
    block(stone, rng, -1.1, 0.8, 0.0, 0.35, 0.7, 0.6, taper=0.8, jitter=0.05)
    face = min(v[1] for v in rings[1] + rings[2]) + 0.1
    shape = ((-0.55, 2.0), (0.05, 1.75), (0.6, 2.0), (0.7, 2.8), (0.3, 3.3), (-0.2, 3.3), (-0.65, 2.9), (-0.7, 2.4))
    centre_x = 0.14 * 2.6
    loft(glyph, [[(centre_x + x, face - 0.17, z) for x, z in shape], [(centre_x + x, face + 0.1, z) for x, z in shape]], W)


def build_stair_run(a):
    """Six solid steps of two studs run and one stud rise, each a little uneven, flanked by two broken walls."""
    rng = a.rng
    stone = a.part("Stone")
    for k in range(1, 7):
        if k == 6:  # the top tread is two blocks, so a vertex stands in the middle of the landing
            for y in (-6.0 + 2.0 * 5.0 + 0.5, -6.0 + 2.0 * 5.0 + 1.5):
                block(stone, rng, rng.uniform(-0.05, 0.05), y, 0.0, 6.0, 13.8, 1.05, taper=0.995, jitter=0.18, worn=False)
            continue
        block(stone, rng, rng.uniform(-0.05, 0.05), -6.0 + 2.0 * (k - 0.5), 0.0, float(k), 13.8, 2.05, taper=0.995,
              jitter=0.18, yaw=0.0, worn=False)
    for side in (-1, 1):
        x0, x1 = (7.2, 8.0) if side > 0 else (-8.0, -7.2)
        low, high = 1.5 + rng.uniform(0.0, 0.5), 5.9 - rng.uniform(0.0, 0.8)
        corners = [(x0, -5.9, 0.0), (x1, -5.9, 0.0), (x1, 5.9, 0.0), (x0, 5.9, 0.0),
                   (x0, -5.9, low), (x1, -5.9, low + 0.3), (x1, 5.9, high), (x0, 5.9, high - 0.4)]
        kc.hexahedron(stone, [(x + rng.uniform(-0.06, 0.06), y + rng.uniform(-0.06, 0.06), z + (rng.uniform(0.0, 0.12)
                                                                                                    if z else 0.0))
                              for x, y, z in corners], W)


