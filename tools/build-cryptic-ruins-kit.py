def build_colonnade(a):
    """Three square columns of stacked drums that drift off line, the last one broken short, with a cracked,
    uneven beam on top, trim bands and rubble at the foot."""
    rng = a.rng
    CLAMP[0] = (12.6, 2.5)
    stone, trim = a.part("Stone"), a.part("Trim")
    for cx, top, drift in ((-10.3, 10.9, 0.05), (0.0, 10.9, -0.06), (10.3, 9.5, 0.07)):
        block(stone, rng, cx, 0.0, 0.0, 0.9, 3.7, 4.4)
        shaft = top - 0.9 - 0.9
        for i in range(4):
            z0 = 0.9 + shaft * i / 4
            block(stone, rng, cx + drift * i * 2 + rng.uniform(-0.1, 0.1), rng.uniform(-0.1, 0.1), z0 - 0.02,
                  z0 + shaft / 4, 3.3 - 0.1 * i, 3.6 - 0.08 * i, taper=0.95, jitter=0.1, yaw=0.07 * (-1) ** i)
        if top > 10.0:
            block(stone, rng, cx, 0.0, top - 0.9, top, 3.8, 4.4, taper=0.92)
        else:
            block(stone, rng, cx + 0.2, 0.2, top - 0.9, 10.7, 3.0, 3.6, taper=0.78)  # a fallen capital wedged under the beam
    block(stone, rng, -5.7, 0.0, 10.9, 12.7, 13.6, 4.4, taper=0.98, jitter=0.1, chip=0.55)
    block(stone, rng, -5.8, 0.1, 12.7, 13.9, 7.4, 3.6, taper=0.9, jitter=0.1)
    block(stone, rng, 7.0, 0.0, 10.7, 12.3, 10.2, 4.4, taper=0.98, jitter=0.1, chip=0.5)
    block(stone, rng, 7.6, 0.2, 12.3, 13.1, 3.8, 3.2, taper=0.85, jitter=0.1)
    for x, y, w, d, h in ((-11.6, 1.5, 1.0, 0.9, 0.7), (-9.7, -1.4, 0.9, 0.9, 0.6), (0.9, 1.6, 0.9, 0.9, 0.6),
                          (11.4, -1.3, 1.0, 1.0, 0.7), (9.4, 1.5, 0.9, 0.9, 0.5)):
        block(stone, rng, x, y, 0.0, h, w, d, taper=0.85, jitter=0.1, yaw=rng.uniform(0.0, 1.0))
    for cx in (-10.3, 0.0):
        plate(trim, rng, cx, -2.3, 10.45, 3.85, 0.3, 0.5)
    plate(trim, rng, 10.3, -2.3, 10.2, 3.85, 0.3, 0.5)
    plate(trim, rng, -5.5, -2.35, 11.8, 13.0, 0.3, 0.5)
    plate(trim, rng, 6.8, -2.35, 11.5, 10.0, 0.3, 0.5)


