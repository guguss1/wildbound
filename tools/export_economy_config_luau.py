"""Generate the Studio economy tuning module from the economy document.

The ```json economy-tuning block of docs/mechanics/wildbound-economy-p0.md stays the single
source of numbers. Studio cannot read it, so this tool writes a Luau copy that the game requires,
`src/wildbound/WildboundEconomyConfig.luau` (Studio: `ReplicatedStorage.WildboundEconomyConfig`).
`simulatorInputs` are left out: they are invented simulator assumptions, not game data.

    python -I -B tools/export_economy_config_luau.py            # print the module
    python -I -B tools/export_economy_config_luau.py --check    # exit 1 if the committed copy differs
    python -I -B tools/export_economy_config_luau.py --write    # rewrite the committed copy
"""

import argparse
import math
import re
import sys
from pathlib import Path

_HERE = str(Path(__file__).resolve().parent)
if _HERE not in sys.path:  # `python -I` does not put the script folder on the path
    sys.path.insert(0, _HERE)

import simulate_economy as eco  # noqa: E402  (the one reader of the tuning block)

REPO = Path(__file__).resolve().parent.parent
MODULE = REPO / "src/wildbound/WildboundEconomyConfig.luau"
EXCLUDED = ("simulatorInputs",)
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
    "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue",
}
HEADER = """-- GENERATED by tools/export_economy_config_luau.py from the ```json economy-tuning block of
-- docs/mechanics/wildbound-economy-p0.md. Do not edit by hand: change the document, then run
--     python -I -B tools/export_economy_config_luau.py --write
-- tools/test_export_economy_config_luau.py fails whenever this copy and the document differ.
-- The simulator's own inputs are left out: they are invented assumptions, not game data.
local function freeze(value)
\tif type(value) == "table" and not table.isfrozen(value) then
\t\tfor _, child in pairs(value) do freeze(child) end
\t\ttable.freeze(value)
\tend
\treturn value
end

return freeze("""


def _scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"non-finite number {value!r}")
        return repr(value)
    if isinstance(value, str):
        if any(not (32 <= ord(ch) < 127) for ch in value):
            raise ValueError(f"only printable ASCII strings are supported: {value!r}")
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    raise ValueError(f"unsupported value {value!r}")


def _key(key):
    if IDENT.match(key) and key not in KEYWORDS:
        return key
    return "[" + _scalar(key) + "]"


def _inline(value):
    return isinstance(value, list) and all(not isinstance(item, (dict, list)) for item in value)


def _value(value, depth):
    pad = "\t" * (depth + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        if all(not isinstance(v, (dict, list)) for v in value.values()):
            flat = "{ " + ", ".join(f"{_key(k)} = {_scalar(v)}" for k, v in value.items()) + " }"
            if len(flat) <= 90:
                return flat
        lines = [f"{pad}{_key(k)} = {_value(v, depth + 1)}," for k, v in value.items()]
        return "{\n" + "\n".join(lines) + "\n" + "\t" * depth + "}"
    if isinstance(value, list):
        if not value:
            return "{}"
        if _inline(value):
            return "{ " + ", ".join(_scalar(item) for item in value) + " }"
        lines = [f"{pad}{_value(item, depth + 1)}," for item in value]
        return "{\n" + "\n".join(lines) + "\n" + "\t" * depth + "}"
    return _scalar(value)


def render(tuning):
    data = {k: v for k, v in tuning.items() if k not in EXCLUDED}
    return HEADER + _value(data, 0) + ")\n"


# ---- Reading the module back (used by the tests) ------------------------------
TOKEN = re.compile(r'\s*(?:(--[^\n]*)|("(?:\\.|[^"\\])*")|(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)|([A-Za-z_][A-Za-z0-9_]*)|(.))')


def _tokens(text):
    out = []
    for comment, string, number, name, other in TOKEN.findall(text):
        if comment:
            continue
        if string:
            out.append(("str", re.sub(r"\\(.)", r"\1", string[1:-1])))
        elif number:
            out.append(("num", float(number) if any(c in number for c in ".eE") else int(number)))
        elif name:
            out.append(("name", name))
        elif other:
            out.append(("op", other))
    return out


def parse_luau(text):
    """Parse the table literal inside `return freeze(...)` back into Python values."""
    body = text.split("return freeze(", 1)[1].rsplit(")", 1)[0]
    tokens, pos = _tokens(body), [0]

    def peek(offset=0):
        index = pos[0] + offset
        return tokens[index] if index < len(tokens) else ("eof", None)

    def take(kind=None, value=None):
        token = peek()
        if (kind and token[0] != kind) or (value is not None and token[1] != value):
            raise ValueError(f"unexpected {token!r}")
        pos[0] += 1
        return token

    def parse_value():
        kind, value = peek()
        if kind == "op" and value == "{":
            return parse_table()
        take()
        if kind in ("str", "num"):
            return value
        if kind == "name" and value in ("true", "false"):
            return value == "true"
        raise ValueError(f"unexpected {value!r}")

    def parse_table():
        take("op", "{")
        keyed, items = {}, []
        while peek() != ("op", "}"):
            if peek() == ("op", "["):
                take()
                key = take("str")[1]
                take("op", "]")
                take("op", "=")
                keyed[key] = parse_value()
            elif peek()[0] == "name" and peek(1) == ("op", "="):
                key = take()[1]
                take()
                keyed[key] = parse_value()
            else:
                items.append(parse_value())
            if peek() == ("op", ","):
                take()
        take("op", "}")
        if keyed and items:
            raise ValueError("mixed table")
        return keyed if keyed else items

    result = parse_value()
    if pos[0] != len(tokens):
        raise ValueError("trailing tokens")
    return result


def check(expected):
    actual = MODULE.read_text(encoding="utf-8").replace("\r\n", "\n") if MODULE.is_file() else None
    if actual == expected:
        print(f"{MODULE.relative_to(REPO).as_posix()} matches the document")
        return 0
    print(f"{MODULE.relative_to(REPO).as_posix()} differs from the document; run --write")
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="exit 1 if the committed module differs")
    group.add_argument("--write", action="store_true", help="rewrite the committed module")
    args = parser.parse_args(argv)
    text = render(eco.load_tuning())
    if args.check:
        return check(text)
    if args.write:
        MODULE.write_text(text, encoding="utf-8", newline="\n")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
