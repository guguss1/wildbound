"""Contracts for the Pradera Arcoiris Luau builder generator (tools/build-pradera-kit.py).

Run from the project root (isolated mode, no bytecode written):

    python -I -B -m unittest discover -s tools -p test_build_pradera_kit.py

The generator renders a parts-only ModuleScript from the layout plan. These tests read the rendered
text and the saved module and re-derive the facts: every planned instance appears exactly once, the
data never closes the Luau long string, the Spanish sign copy is present, the palette matches the
design table, colliders and query parts are only where the design allows, block keywords balance,
and the written module is fresh. Nothing here runs Luau or touches Studio.
"""

import importlib.util
import json
import re
import unittest
from pathlib import Path

import plan_pradera_layout as plan

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parent

spec = importlib.util.spec_from_file_location("build_pradera_kit", TOOLS / "build-pradera-kit.py")
kit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kit)

# Design table (docs/design/wildbound-biome-pradera.md section 2), restated here.
PALETTE = {"grass": "A8E6B0", "lavender": "D9C8F0", "path": "F5E6C8", "stem": "FFF4E0", "capCoral": "F28B9B",
           "capSky": "8FD3F4", "capButter": "F9E27A", "spot": "FFFFFF", "pond": "B9B3CF", "wood": "C98F5A",
           "neonSun": "FFD23F", "cloudGrey": "B4A8D2", "cloudBelly": "8C7FB0"}
PROP_NAMES = ("PA_GiantMushroom", "PA_PuffTree", "PA_MushroomRing", "PA_PuffFlower", "PA_SunflowerPost",
              "PA_HillBoulder", "PA_RainbowGate", "PA_Pinwheel", "PA_SetaTrueno")
SPANISH = ("Pradera Arcoíris", "Plaza del Molino", "Charca de la Nube Gruñona", "sal del círculo", "Girasoles: a salvo")
MAX_PARTS = 1700


def luau_block_balance(text):
    """Rough Luau block check: function/do/if/repeat open, end/until close. Strings and comments stripped."""
    text = re.sub(r"\[==\[.*?\]==\]", "", text, flags=re.S)
    text = re.sub(r"--.*", "", text)
    text = re.sub(r"'(?:\\.|[^'\\])*'", "''", text)
    opens = len(re.findall(r"\bfunction\b|\bdo\b|\bif\b|\brepeat\b", text)) - len(re.findall(r"\belseif\b", text)) * 0
    closes = len(re.findall(r"\bend\b|\buntil\b", text))
    return opens, closes


class Rendering(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.layout = json.loads(plan.to_json(plan.generate(plan.DEFAULT_SEED)))
        cls.module = kit.render(cls.layout)

    def test_every_instance_is_a_row_exactly_once(self):
        rows = self.module.split("local ROWS = [==[\n", 1)[1].split("\n]==]", 1)[0].split("\n")
        self.assertEqual(len(rows), len(self.layout["instances"]))
        ids = [r.split("|")[0] for r in rows]
        self.assertEqual(sorted(ids), sorted(i["id"] for i in self.layout["instances"]))
        for row, inst in zip(rows, self.layout["instances"]):
            fields = row.split("|")
            self.assertEqual(len(fields), 9, row)
            self.assertEqual(fields[1], inst["name"])
            self.assertEqual(float(fields[2]), inst["x"])
            self.assertEqual(float(fields[3]), inst["y"])
            self.assertEqual(float(fields[4]), inst["z"])
            self.assertEqual(fields[7], inst["zone"])
            expected = inst.get("cap") or inst.get("puff") or inst.get("sun_circle") or "-"
            self.assertEqual(fields[8], expected)

    def test_data_block_carries_the_plan_tables(self):
        data = json.loads(self.module.split("local DATA = [==[", 1)[1].split("]==]", 1)[0])
        for key in ("world", "terrain", "zones", "beast", "nests", "sun_circles", "route"):
            self.assertEqual(data[key], self.layout[key], key)
        self.assertNotIn("]==]", json.dumps(self.layout, ensure_ascii=False))
        self.assertEqual(len(data["nests"]), 5)
        self.assertEqual(data["nests"][-1]["species"], "Relampino")

    def test_header_names_the_plan_seed_and_checksum(self):
        head = self.module.splitlines()[0]
        self.assertIn("GENERATED by tools/build-pradera-kit.py", head)
        self.assertIn("seed %d" % self.layout["seed"], head)
        rows = self.module.split("local ROWS = [==[\n", 1)[1].split("\n]==]", 1)[0]
        data = self.module.split("local DATA = [==[", 1)[1].split("]==]", 1)[0]
        self.assertIn("Adler-32 %d" % kit.adler32(rows + data), head)

    def test_every_prop_has_a_builder(self):
        for name in PROP_NAMES:
            self.assertIn("function props.%s(parent, inst)" % name, self.module, name)
        self.assertIn("function Builder.build(parent, origin)", self.module)
        for fn in ("buildTerrain", "buildNests", "buildSunCircles", "buildBeast", "buildSigns", "buildMarkers", "buildProps"):
            self.assertIn("local function %s(root)" % fn, self.module, fn)

    def test_spanish_signs_and_english_code(self):
        for text in SPANISH:
            self.assertIn(text, self.module, text)
        self.assertIn("SignKey", self.module)
        self.assertEqual(len(kit.SIGNS), 4)
        for key, text, *_ in kit.SIGNS:
            self.assertTrue(key.startswith("pradera"), key)
            self.assertNotIn("'", text, "sign copy must not need escaping")

    def test_palette_matches_the_design_table(self):
        for name, hex_value in PALETTE.items():
            r, g, b = kit.hex_to_rgb(hex_value)
            self.assertIn("%s = Color3.fromRGB(%d, %d, %d)," % (name, r, g, b), self.module, name)

    def test_colliders_and_queries_stay_where_the_design_allows(self):
        # Only terrain, path, pond, stems, trunks, the Seta Trueno, gate posts, boulders and steps collide; only
        # stems, trunks, hills, the floor and the Roof boxes answer queries (the roof sense needs them).
        # A call may wrap onto a second line, so each flag is judged with the line before it (the call's start).
        lines = self.module.splitlines()

        def statements(flag):
            return [(lines[i - 1] if i else "") + " " + line for i, line in enumerate(lines) if flag in line]

        collide_lines = statements("collide = true")
        self.assertGreaterEqual(len(collide_lines), 8)
        for statement in collide_lines:
            self.assertTrue(any(word in statement for word in ("Floor", "Hill", "Pond", "Path", "Stem", "Trunk", "Cap",
                                                               "Post", "Rock", "Step")), statement)
        query_lines = statements("query = true")
        self.assertGreaterEqual(len(query_lines), 5)
        for statement in query_lines:
            self.assertTrue(any(word in statement for word in ("Floor", "Hill", "Stem", "Trunk", "Roof")), statement)
        self.assertIn("CollectionService:AddTag(item, 'WildboundRoof')", self.module)
        self.assertIn("item.CanTouch = false", self.module)
        self.assertIn("item.Anchored = true", self.module)
        self.assertNotIn("Instance.new('MeshPart')", self.module)
        self.assertNotIn("Instance.new('SpecialMesh')", self.module)
        self.assertNotIn("rbxassetid", self.module)
        self.assertNotIn("InsertService", self.module)

    def test_luau_blocks_balance(self):
        opens, closes = luau_block_balance(self.module)
        self.assertEqual(opens, closes)
        self.assertEqual(self.module.count("[==["), self.module.count("]==]"))
        self.assertTrue(self.module.rstrip().endswith("return Builder"))

    def test_part_count_is_exact_and_under_the_cap(self):
        counts = kit.part_count(self.layout)
        by_prop = counts["by_prop"]
        self.assertEqual(sum(by_prop.values()), len(self.layout["instances"]))
        props = sum(kit.PARTS[name] * n for name, n in by_prop.items())
        self.assertEqual(counts["props"], props)
        self.assertEqual(counts["nests"], sum(4 + 5 * n["adults"] for n in self.layout["nests"]))
        self.assertEqual(counts["sun_circles"], 2 * len(self.layout["sun_circles"]))
        self.assertEqual(counts["hills"], 2 * len(self.layout["terrain"]["hills"]))
        self.assertEqual(counts["total"], props + counts["nests"] + counts["sun_circles"] + counts["hills"] + counts["path"]
                         + counts["signs"] + counts["beast"] + counts["fixed"])
        self.assertLessEqual(counts["total"], MAX_PARTS)
        self.assertIn("Builder.EXPECTED_PARTS = %d" % counts["total"], self.module)
        self.assertEqual(kit.PARTS, {name: plan.PROPS[name]["parts"] for name in PROP_NAMES},
                         "the planner's part estimate and the generator agree per prop")

    def test_rendering_is_deterministic(self):
        self.assertEqual(self.module, kit.render(self.layout))

    def test_validation_rejects_bad_plans(self):
        broken = json.loads(json.dumps(self.layout))
        broken["instances"][0]["name"] = "PA_Unknown"
        with self.assertRaises(ValueError):
            kit.render(broken)
        broken = json.loads(json.dumps(self.layout))
        broken["instances"][1]["id"] = broken["instances"][0]["id"]
        with self.assertRaises(ValueError):
            kit.render(broken)
        broken = json.loads(json.dumps(self.layout))
        broken["nests"] = broken["nests"][:4]
        with self.assertRaises(ValueError):
            kit.render(broken)


class WrittenFiles(unittest.TestCase):
    def test_saved_module_is_fresh(self):
        if not kit.MODULE.exists() or not kit.PLAN.exists():
            self.skipTest("module not written yet")
        layout = json.loads(kit.PLAN.read_text(encoding="utf-8"))
        self.assertEqual(kit.MODULE.read_text(encoding="utf-8"), kit.render(layout))
        self.assertEqual(kit.MODULE.read_bytes().count(b"\r\n"), 0, "LF line endings")

    def test_saved_report_matches_the_module(self):
        if not kit.REPORT.exists() or not kit.MODULE.exists():
            self.skipTest("report not written yet")
        report = json.loads(kit.REPORT.read_text(encoding="utf-8"))
        self.assertEqual(report["module_adler32"], kit.adler32(kit.MODULE.read_text(encoding="utf-8")))
        layout = json.loads(kit.PLAN.read_text(encoding="utf-8"))
        self.assertEqual(report["parts"], kit.part_count(layout))
        self.assertIn("unvalidated", report["status"])


if __name__ == "__main__":
    unittest.main()
