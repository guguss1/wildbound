"""Build the original Rock and Caves prop kit (RC_) in a fresh headless Blender scene.

Run: "D:/blender/blender.exe" --background --factory-startup --python tools/build-rock-caves-kit.py
Set ROCK_CAVES_KIT_MODE=verify-fbx to re-import the exports in fresh scenes instead.
Under plain Python this file does a dry run: it counts triangles, checks closure and clearance.

1 Blender unit = 1 stud. Each prop is an Empty root at the ground-level pivot with one mesh
child per material, because a Roblox MeshPart holds one colour and one material. The tunnel
modules share one closed C-shaped profile (tools/cave_profile.py): their end rings are exactly
that profile, so any straight or bend joins any other. There is no floor mesh (a floor would fail
clear_width); the floor is a collision box in the report. All geometry is scripted here. Nothing
is downloaded, generated by a service or uploaded, and every value is unvalidated: never imported
into Roblox. Spec: bible 5.1, 5.2, 5.5.
"""

