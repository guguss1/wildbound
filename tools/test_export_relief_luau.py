"""Contracts for tools/export_relief_luau.py (task R2).

    python -I -B -m unittest discover -s tools -p test_export_relief_luau.py
"""

import json
import re
import unittest
from pathlib import Path

import export_relief_luau as exporter

PLAN = Path(__file__).resolve().parent.parent / "assets/maps/forest-layout/relief-v1.json"
ROW = re.compile(r"^(S|P|T)\|(.*)$")


def parse(module):
    """Reads the generated rows back, as the Luau module does."""
    body = module.split("[==[", 1)[1].split("]==]", 1)[0]
    segments, samples, trees = [], [], []
    for line in body.strip().splitlines():
        kind, rest = ROW.match(line).groups()
        fields = rest.split("|")
        if kind == "S":
            segments.append({"id": fields[0], "feature": fields[1], "a": [float(fields[2]), float(fields[3])],
                             "b": [float(fields[4]), float(fields[5])], "height": float(fields[6]),
                             "crestWidth": float(fields[7]), "slopeDeg": float(fields[8])})
        elif kind == "P":
            samples.append({"x": float(fields[0]), "z": float(fields[1]), "y": float(fields[2])})
        else:
            trees.append(fields[0])
    return segments, samples, trees


class ExportRelief(unittest.TestCase):
    def test_export_round_trips_segments(self):
        plan = json.loads(PLAN.read_text(encoding="utf-8"))
        module = exporter.render(plan)
        segments, samples, trees = parse(module)
        self.assertEqual(segments, plan["segments"])
        self.assertEqual(samples, plan["samples"])
        self.assertEqual(trees, plan["removedTrees"])
        self.assertIn("floorTop = 0.5", module)
        self.assertTrue(module.startswith("-- GENERATED by tools/export_relief_luau.py"))

    def test_export_refuses_text_that_closes_the_long_string(self):
        plan = json.loads(PLAN.read_text(encoding="utf-8"))
        plan["segments"][0]["feature"] = "bad]==]"
        with self.assertRaises(ValueError):
            exporter.render(plan)

    def test_adler32_is_stable(self):
        module = exporter.render(json.loads(PLAN.read_text(encoding="utf-8")))
        self.assertEqual(exporter.adler32(module), exporter.adler32(module))


if __name__ == "__main__":
    unittest.main()
