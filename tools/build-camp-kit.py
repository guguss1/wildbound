    rough_tube(iron, rng, [(0.0, 0.0, 7.95), (0.0, 0.0, 7.6), (0.0, 0.0, 7.25)], [0.09, 0.09, 0.09], sides=4, rough=0.0)
    kc.box(iron, (0.0, 0.0, 7.8), (0.4, 0.4, 0.3), W)
    kc.lathe(lamp, [(0.38, 0.0), (0.5, 0.3), (0.5, 0.6), (0.3, 0.9)], 6, W, center=(0.0, 0.0, 6.35))


