def stone(part, rng, x, y, radius, height, sides=5, taper=0.6, rings=2, squash=1.0):
    """Faceted boulder: a jittered polygon stack that narrows toward a flat top, resting on Z 0."""
    phase = rng.uniform(0.0, TAU)

    def ring(scale, z):
        out = []
        for k in range(sides):
            angle = phase + TAU * k / sides + rng.uniform(-0.18, 0.18)
            reach = radius * scale * rng.uniform(0.84, 1.14)
            out.append((x + math.cos(angle) * reach, y + math.sin(angle) * reach * squash, z))
        return out

    stack = [ring(1.0, 0.0), ring(taper, height)] if rings == 2 else \
        [ring(0.9, 0.0), ring(1.0, height * 0.5), ring(taper, height)]
    loft(part, stack, W)


def rough_tube(part, rng, points, radii, sides=6, rough=0.07, twist=0.0, flutes=0.0):
    """Faceted limb or log: per-vertex jitter, grooves that persist along the length, a slow spiral."""
    frames = kc.path_frames(points)
    phase = rng.uniform(0.0, TAU)
    groove = [1.0 + flutes * (rng.uniform(0.3, 1.0) if k % 2 else -rng.uniform(0.3, 1.0)) for k in range(sides)]
    rings, start, end = [], "cap", "cap"
    for index, (point, radius) in enumerate(zip(points, radii)):
        if radius <= 0.0:
            if index == 0:
                start = point
            else:
                end = point
            continue
        side, normal, _ = frames[index]
        ring = []
        for k in range(sides):
            angle = phase + twist * index + TAU * k / sides
            amount = radius * groove[k] * (1.0 + rng.uniform(-rough, rough))
            ring.append(add(point, add(mul(side, math.cos(angle) * amount), mul(normal, math.sin(angle) * amount))))
        rings.append(ring)
    loft(part, rings, W, start, end)


def tongue(part, base, direction, radius, height, sides=5, phase=0.0):
    """One flame tongue: a short faceted prism that narrows to a point."""
    kc.lathe(part, [(radius, 0.0), (radius * 0.78, height * 0.45), (0.0, height)], sides, W, center=base,
             frame=kc.basis(direction), phase=phase)


def egg(part, center, radius, half_height, axis, sides=5, phase=0.0):
    """An ovoid: a short faceted lathe with a small flat cap at each pole."""
    kc.lathe(part, kc.arc_profile(radius, half_height, 2, bottom=-72.0, top=72.0), sides, W, center=center,
             frame=kc.basis(axis), phase=phase)


def moss_clump(part, rng, x, y, z, radius, height, sides=5):
    kc.lathe(part, kc.arc_profile(radius, height, 2, bottom=0.0), sides, W, center=(x, y, z),
             phase=rng.uniform(0.0, TAU), scale=(1.0, rng.uniform(0.8, 1.0)))


