def build_campfire(asset):
    rng = asset.rng
    stones, logs, flame = asset.part("Stones"), asset.part("Logs"), asset.part("Neon_Flame")
    # Eight stones in a loose ring, low enough that the fire reads over them.
    for k in range(8):
        angle = TAU * k / 8 + rng.uniform(-0.08, 0.08)
        radius = rng.uniform(2.3, 2.5)
        stone(stones, rng, math.cos(angle) * radius, math.sin(angle) * radius, rng.uniform(0.62, 0.78),
              rng.uniform(0.6, 0.85), sides=5, taper=0.68)
    # Four logs leaning in to a teepee and one laid across the foot of it.
    for k, angle in enumerate((0.3, 1.9, 3.5, 5.1)):
        tilt = rng.uniform(0.0, 0.2)
        foot = (math.cos(angle) * 1.45, math.sin(angle) * 1.45, 0.25)
        top = (math.cos(angle + tilt) * 0.25, math.sin(angle + tilt) * 0.25, 2.1 + 0.2 * (k % 2))
        mid = tuple((a + b) / 2 + rng.uniform(-0.04, 0.04) for a, b in zip(foot, top))
        rough_tube(logs, rng, [foot, mid, top], [0.34, 0.31, 0.24], sides=5, rough=0.08, twist=0.4)
    rough_tube(logs, rng, [(-1.3, 0.9, 0.35), (0.0, 0.8, 0.4), (1.3, 0.95, 0.35)], [0.28, 0.3, 0.27], sides=5,
               rough=0.08)
    # Three flame tongues, the tallest in the middle.
    tongue(flame, (0.0, 0.0, 0.7), (0.05, 0.0, 1.0), 0.55, 2.9, phase=0.2)
    tongue(flame, (0.45, 0.2, 0.7), (0.5, 0.1, 1.0), 0.4, 2.0, phase=0.5)
    tongue(flame, (-0.4, -0.25, 0.7), (-0.5, -0.2, 1.0), 0.38, 1.7, phase=0.1)


def build_camp_shelter(asset):
    rng = asset.rng
    canvas, poles, rope = asset.part("Canvas"), asset.part("Poles"), asset.part("Rope")
    ridge_z, spread = 4.5, 2.85
    slope = (spread, -ridge_z)
    length = math.hypot(*slope)
    normal = (ridge_z / length, 0.0, spread / length)
    # Two canvas panels, each a thin band that droops to a ragged hem near the ground.
    for side in (1, -1):
        rings = []
        for y in (-3.9, -1.95, 0.0, 1.95, 3.9):
            hem = (side * (spread + rng.uniform(-0.12, 0.14)), y, rng.uniform(0.12, 0.42))
            ridge = (side * 0.04, y, ridge_z + rng.uniform(-0.04, 0.04))
            out_n = (side * normal[0] * 0.06, 0.0, normal[2] * 0.06)
            rings.append([add(ridge, out_n), add(hem, out_n), add(hem, mul(out_n, -1)), add(ridge, mul(out_n, -1))])
        loft(canvas, rings, W)
    # A ridge pole and two crossed pole pairs, with pegs at the hem corners.
    rough_tube(poles, rng, [(0.0, -4.0, 4.75), (0.0, 0.0, 4.8), (0.0, 4.0, 4.75)], [0.16, 0.2, 0.16], sides=5,
               rough=0.06)
    for y in (-3.6, 3.6):
        for side in (1, -1):
            rough_tube(poles, rng, [(side * 2.85, y, 0.0), (side * 1.45, y, 2.35), (-side * 0.14, y, 4.7)],
                       [0.2, 0.18, 0.14], sides=5, rough=0.06)
    for y in (-3.8, 3.8):
        for side in (1, -1):
            rough_tube(poles, rng, [(side * 2.95, y, 0.0), (side * 2.9, y, 0.5)], [0.12, 0.09], sides=5,
                       rough=0.05)
    # Lashings: chunky bands at the apex of each pole pair and two along the ridge.
    for y in (-3.6, 3.6):
        kc.box(rope, (0.0, y, 4.5), (0.62, 0.5, 0.42), W, yaw=rng.uniform(-0.2, 0.2))
    for y in (-1.2, 1.2):
        kc.box(rope, (0.0, y, 4.82), (0.4, 0.5, 0.36), W, yaw=rng.uniform(-0.2, 0.2))
    for side in (1, -1):
        kc.box(rope, (side * 1.45, 3.6, 2.35), (0.42, 0.42, 0.36), W, yaw=rng.uniform(-0.3, 0.3))


def build_hatch_altar(asset):
    rng = asset.rng
    stone_part, moss, runes = asset.part("Stone"), asset.part("Moss"), asset.part("Neon_Rune")
    # A stepped octagonal pedestal with a shallow dish on top and a raised rim.
    profile = [(2.5, 0.0), (2.5, 0.5), (2.0, 0.72), (1.85, 0.72), (1.62, 1.9), (1.98, 2.3), (2.2, 2.7),
               (2.2, 3.0), (1.5, 3.0), (1.1, 2.45), (0.0, 2.35)]
    kc.lathe(stone_part, profile, 8, W, jitter=0.035, rng=rng, twist=0.03, phase=0.2)
    # Four glowing runes, one on each side of the column.
    rune = [(0.0, -0.5), (0.2, -0.28), (0.2, 0.28), (0.0, 0.5), (-0.2, 0.28), (-0.2, -0.28)]
    for k in range(4):
        angle = math.pi / 4 + k * math.pi / 2
        radial = (math.cos(angle), math.sin(angle), 0.0)
        tangent = (-math.sin(angle), math.cos(angle), 0.0)
        origin = (radial[0] * 1.68, radial[1] * 1.68, 1.3)
        slab(runes, rune, origin, tangent, (0.0, 0.0, 1.0), radial, 0.12, W)
    for angle, z, r in ((0.5, 0.72, 0.38), (2.7, 0.72, 0.3), (4.4, 0.72, 0.34)):
        moss_clump(moss, rng, math.cos(angle) * 1.95, math.sin(angle) * 1.95, z, r, r * 0.9)


