def build_yeti():
    asset = Asset_("GD_Yeti", seed=131)
    hide, ice, mask, hands, eye = (asset.part(n) for n in ("Hide", "Ice", "Mask", "Hands", "Neon_Eye"))
    torso_w = chain(("Pelvis", "Spine", "Chest"), (4.9, 6.3, 8.2), axis=2)

    # Torso: a long sloping barrel from the rump up to the shoulder hump, wider than deep.
    spine = [(0, 3.4, 4.5), (0, 2.3, 5.0), (0, 0.9, 6.4), (0, -0.5, 7.9), (0, -1.5, 8.6)]
    radii = [1.5, 2.3, 2.7, 2.9, 2.4]
    mark = len(hide.vertices)
    tube(hide, spine, radii, 8, torso_w, phase=0.2, squash=1.2)
    roughen(asset, hide, mark, 0.12)
    # The hump: a rounded mass above the shoulders, the tallest thing on the animal.
    mark = len(hide.vertices)
    lathe(hide, kc.arc_profile(2.6, 2.7, 4), 8, rigid("Chest"), center=(0, -1.0, 8.6),
          frame=kc.basis((0, -0.35, 1)), scale=(1.15, 1.0), phase=0.3)
    roughen(asset, hide, mark, 0.1)

    # Broad shoulders carry the arms.
    for side, upper in ((1, "UpperArm.L"), (-1, "UpperArm.R")):
        shoulder = (side * 3.1, -1.3, 8.4)
        weigh = blend("Chest", upper, (side * 2.4, -1.2, 9.0), (side * 3.6, -1.6, 7.4), 0.0, 1.0)
        mark = len(hide.vertices)
        lathe(hide, kc.arc_profile(1.7, 1.6, 4), 8, weigh, center=shoulder, frame=kc.basis((side, 0, 0.3)))
        roughen(asset, hide, mark, 0.08)

    # Neck and head: the head hangs low and forward, well under the hump.
    neck = [(0, -1.6, 8.2), (0, -2.4, 7.7), (0, -3.0, 7.1)]
    tube(hide, neck, [1.6, 1.5, 1.45], 6, blend("Chest", "Head", (0, -1.8, 8.2), (0, -3.0, 7.2), 0.0, 1.0),
         squash=1.25)
    front = kc.basis((0, -1, 0))
    lathe(hide, kc.arc_profile(2.0, 1.5, 4), 8, rigid("Head"), center=(0, -2.9, 6.8), frame=front,
          scale=(1.0, 0.85), phase=0.3)

    # Arms: long and thick, bowed outward, ending in knuckles on the ground.
    for side, upper, fore, hand in ((1, "UpperArm.L", "Forearm.L", "Hand.L"), (-1, "UpperArm.R", "Forearm.R", "Hand.R")):
        shoulder, elbow, wrist = (side * 3.1, -1.2, 8.6), (side * 4.2, -2.2, 5.0), (side * 4.5, -3.4, 1.4)
        arm_w = zone_weights((hand, fore, upper), (1.4, 5.0), 0.6)
        mark = len(hide.vertices)
        tube(hide, [shoulder, elbow, wrist], [1.5, 1.3, 1.0], 8, arm_w, phase=0.2)
        roughen(asset, hide, mark, 0.08)

    # Hind legs: short and folded, on flat feet.
    for side, thigh, shin, foot in ((1, "Thigh.L", "Shin.L", "Foot.L"), (-1, "Thigh.R", "Shin.R", "Foot.R")):
        hip, knee, ankle = (side * 1.9, 2.6, 4.7), (side * 2.7, 1.4, 2.9), (side * 2.7, 2.3, 0.9)
        leg_w = zone_weights((foot, shin, thigh), (1.0, 2.9), 0.4)
        mark = len(hide.vertices)
        tube(hide, [hip, madd(hip, sub(knee, hip), 0.5), knee], [1.7, 1.45, 1.2], 8,
             blend("Pelvis", thigh, hip, knee, 0.0, 0.5))
        tube(hide, [knee, madd(knee, sub(ankle, knee), 0.5), ankle], [1.2, 1.0, 0.85], 8, leg_w)
        roughen(asset, hide, mark, 0.08)
        box(hide, (side * 2.7, 1.6, 0.4), (2.0, 3.0, 0.8), rigid(foot))

    # Matted hide: ragged clumps hanging from the flanks, belly, shoulders and rump.
    flank = ((2.4, 4.9, 2.4), (1.5, 5.8, 2.8), (0.4, 6.8, 3.1), (-0.7, 7.6, 3.2))
    for y, z, w in flank:
        for side in (1, -1):
            pyramid(hide, (side * w * 0.88, y, z - 0.1), (side * 0.6, 0.55, -1.0), 0.62, 2.1, torso_w)
    for y, z in ((2.8, 3.8), (1.2, 4.7), (-0.2, 5.9)):
        pyramid(hide, (0, y, z), (0, 0.3, -1.0), 0.65, 2.0, torso_w)
    for side, upper, fore in ((1, "UpperArm.L", "Forearm.L"), (-1, "UpperArm.R", "Forearm.R")):
        pyramid(hide, (side * 3.9, -1.4, 7.6), (side * 0.7, 0.2, -1.0), 0.6, 2.2, rigid(upper))
        pyramid(hide, (side * 4.6, -2.0, 5.8), (side * 0.6, 0.3, -1.0), 0.55, 2.0, rigid(upper))
        pyramid(hide, (side * 4.9, -2.9, 3.1), (side * 0.5, 0.2, -1.0), 0.5, 1.7, rigid(fore))
    for x in (-1.5, 0.0, 1.5):
        pyramid(hide, (x, 3.9, 4.2), (x * 0.2, 0.6, -1.0), 0.6, 1.9, rigid("Pelvis"))

    # Ice plates: shingles down the back, flank plates beside them, shoulder and forearm crust.
    def back_point(s_, phi):
        """A point on the torso barrel at fraction s_ and angle phi from the top, with its normal."""
        point, tangent = along(spine, s_)
        radius = radii[min(int(s_ * 4), 3)] * (1 - (s_ * 4) % 1) + radii[min(int(s_ * 4) + 1, 4)] * ((s_ * 4) % 1)
        top = unit(cross((1, 0, 0), tangent))
        top = top if top[2] > 0 else mul(top, -1)
        lateral = (math.sin(phi) * radius * 1.2, 0.0, 0.0)
        spot = add(add(point, mul(top, math.cos(phi) * radius)), lateral)
        normal = unit(add(mul(top, math.cos(phi)), (math.sin(phi) / 1.2, 0.0, 0.0)))
        return spot, normal

    for s_, size, thick in ((0.22, 1.3, 0.42), (0.37, 1.55, 0.44), (0.52, 1.6, 0.45), (0.66, 1.5, 0.45)):
        spot, normal = back_point(s_, 0.0)
        plate(asset, ice, spot, normal, size, thick, torso_w, stretch=1.25)
    for s_ in (0.32, 0.54):
        for phi in (0.95, -0.95):
            spot, normal = back_point(s_, phi)
            plate(asset, ice, spot, normal, 1.15, 0.4, torso_w, sides=6, bevel=0.0)
    for side in (1, -1):
        plate(asset, ice, (side * 4.0, -1.6, 8.9), unit((side * 0.85, -0.05, 0.5)), 1.0, 0.4, rigid("UpperArm.L" if side > 0 else "UpperArm.R"),
              sides=6, bevel=0.0)
    for side, fore in ((1, "Forearm.L"), (-1, "Forearm.R")):
        elbow, wrist = (side * 4.2, -2.2, 5.0), (side * 4.5, -3.4, 1.4)
        for s_ in (0.18, 0.66):
            point = kc.lerp(elbow, wrist, s_)
            normal = unit((side * 0.45, -0.85, 0.1))
            plate(asset, ice, madd(point, normal, 1.0), normal, 1.15, 0.38, rigid(fore), stretch=0.7, bevel=0.0)

    # The face: one flat shale plate, cracked at a corner, under a heavy brow ledge.
    face = [(-1.7, -0.9), (-1.8, 0.4), (-1.0, 1.2), (1.1, 1.3), (1.8, 0.6), (1.7, -0.5), (0.9, -1.35), (-0.9, -1.2)]
    roll = 0.10
    u = (math.cos(roll), 0.0, math.sin(roll))
    v = (-math.sin(roll), 0.0, math.cos(roll))
    slab(mask, face, (0, -4.0, 6.7), u, v, (0, -1, 0), 0.5, rigid("Head"))
    shard = [(-0.6, -0.5), (-0.7, 0.4), (0.3, 0.7), (0.9, 0.0), (0.5, -0.6)]
    slab(mask, shard, (1.15, -4.25, 6.1), u, v, (0, -1, 0), 0.25, rigid("Head"), bevel=0.2)
    brow = [(-1.9, 0.0), (-1.5, 0.5), (1.5, 0.5), (1.9, 0.0), (1.6, -0.4), (-1.6, -0.4)]
    slab(mask, brow, (0, -3.9, 7.95), (1, 0, 0), (0, -0.45, -1.0), unit(cross((1, 0, 0), (0, -0.45, -1.0))), 0.45,
         rigid("Head"), bevel=0.25)
    jaw = [(-1.5, 0.0), (-1.1, 0.5), (1.1, 0.5), (1.5, 0.0), (0.9, -0.4), (-0.9, -0.4)]
    slab(mask, jaw, (0, -3.7, 5.35), (1, 0, 0), (0, -0.6, 1.0), unit(cross((1, 0, 0), (0, -0.6, 1.0))), 0.45,
         rigid("Head"), bevel=0.25)

    # Two narrow cold eyes on the plate.
    for side in (1, -1):
        prism(eye, (side * 0.85, -4.5, 6.85), (0, -1, 0), 0.22, 0.14, rigid("Head"), sides=6, scale=(1.9, 0.45))

    # Hands: big dark knuckle blocks that take the weight.
    for side, hand in ((1, "Hand.L"), (-1, "Hand.R")):
        weigh = rigid(hand)
        wrist = (side * 4.5, -3.4, 1.4)
        prism(hands, madd(wrist, (0, 0, 1), 0.3), (0, 0, -1), 1.0, 0.6, weigh, sides=5)
        box(hands, (side * 4.6, -3.7, 0.95), (1.9, 1.7, 1.2), weigh, taper=0.8)
        for k in range(4):
            box(hands, (side * (3.75 + 0.5 * k + (0.2 if side < 0 else 0)), -4.5, 0.4), (0.5, 0.8, 0.8), weigh)
        box(hands, (side * 3.5, -3.3, 0.6), (0.7, 1.0, 0.8), weigh)

    asset.bone("Root", None, (0, 0.4, 0), (0, 0.4, 0.8))
    asset.bone("Pelvis", "Root", (0, 2.6, 4.8), (0, 1.8, 5.6))
    asset.bone("Spine", "Pelvis", (0, 1.8, 5.6), (0, 0.5, 7.0))
    asset.bone("Chest", "Spine", (0, 0.5, 7.0), (0, -1.0, 8.6))
    asset.bone("Neck", "Chest", (0, -1.8, 8.0), (0, -2.9, 7.3))
    asset.bone("Head", "Neck", (0, -2.9, 7.3), (0, -4.2, 6.6))
    for side, suffix in ((1, ".L"), (-1, ".R")):
        asset.bone("UpperArm" + suffix, "Chest", (side * 3.1, -1.2, 8.6), (side * 4.2, -2.2, 5.0))
        asset.bone("Forearm" + suffix, "UpperArm" + suffix, (side * 4.2, -2.2, 5.0), (side * 4.5, -3.4, 1.4))
        asset.bone("Hand" + suffix, "Forearm" + suffix, (side * 4.5, -3.4, 1.4), (side * 4.6, -4.4, 0.5))
    for side, suffix in ((1, ".L"), (-1, ".R")):
        asset.bone("Thigh" + suffix, "Pelvis", (side * 1.9, 2.6, 4.7), (side * 2.7, 1.4, 2.9))
        asset.bone("Shin" + suffix, "Thigh" + suffix, (side * 2.7, 1.4, 2.9), (side * 2.7, 2.3, 0.9))
        asset.bone("Foot" + suffix, "Shin" + suffix, (side * 2.7, 2.3, 0.9), (side * 2.6, 0.4, 0.3))
    # The rig lists bones in the order the Silueta set does.
    order = {name: i for i, name in enumerate(motion.BONES["GD_Yeti"])}
    asset.bones.sort(key=lambda b: order[b[0]])
    return asset


