def aim_camera(camera, points, width, height, azimuth, elevation, margin=1.14):
    """kit_common.frame_camera with a free direction: azimuth 0 faces the front of the guardian."""
    from mathutils import Matrix, Vector
    az, el = math.radians(azimuth), math.radians(elevation)
    backward = Vector((math.sin(az) * math.cos(el), -math.cos(az) * math.cos(el), math.sin(el)))
    right = Vector((math.cos(az), math.sin(az), 0.0))
    up = backward.cross(right)
    xs = [right.dot(Vector(p)) for p in points]
    ys = [up.dot(Vector(p)) for p in points]
    center = right * ((min(xs) + max(xs)) / 2) + up * ((min(ys) + max(ys)) / 2)
    extent_x, extent_y = (max(xs) - min(xs)) * margin, (max(ys) - min(ys)) * margin
    aspect = width / height
    camera.data.ortho_scale = max(extent_x, extent_y * aspect) if aspect >= 1 else max(extent_x / aspect, extent_y)
    camera.location = center + backward * 500.0
    camera.rotation_euler = Matrix((right, up, backward)).transposed().to_euler()


