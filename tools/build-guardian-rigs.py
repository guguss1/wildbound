def zone_weights(bones, cuts, half, axis=2):
    """Bones listed from the lowest coordinate up, handing over around each cut by +-half.

    Two influences at most, as long as neighbouring cuts are more than 2 * half apart.
    """
    def weigh(v):
        c = v[axis]
        for index, cut in enumerate(cuts):
            if abs(c - cut) < half:
                s = (c - (cut - half)) / (2 * half)
                s = s * s * (3.0 - 2.0 * s)
                return {bones[index]: 1.0 - s, bones[index + 1]: s}
        index = sum(1 for cut in cuts if c > cut)
        return {bones[index]: 1.0}

    return weigh


def roughen(asset, part, start, amount):
    """Nudge the vertices added since `start`, so matted shapes are not perfectly regular."""
    for index in range(start, len(part.vertices)):
        x, y, z = part.vertices[index]
        part.vertices[index] = (x + asset.rng.uniform(-amount, amount), y + asset.rng.uniform(-amount, amount),
                                z + asset.rng.uniform(-amount, amount))


def pyramid(part, base, direction, radius, height, weigh, sides=3):
    lathe(part, [(radius, 0.0), (0.0, height)], sides, weigh, center=base, frame=kc.basis(direction))


def prism(part, base, direction, radius, height, weigh, sides=6, scale=(1.0, 1.0)):
    lathe(part, [(radius, 0.0), (radius, height)], sides, weigh, center=base, frame=kc.basis(direction),
          scale=scale)


def plate(asset, part, point, normal, size, thickness, weigh, sink=0.12, sides=6, stretch=1.0, bevel=0.3):
    """An irregular shingle lying on a surface, tilted to its normal, with a chamfered rim."""
    u, v, n = kc.basis(normal)
    outline = []
    for k in range(sides):
        angle = math.tau * k / sides + 0.2
        reach = size * asset.rng.uniform(0.88, 1.08)
        outline.append((math.cos(angle) * reach * stretch, math.sin(angle) * reach))
    slab(part, outline, madd(point, n, -sink), u, v, n, thickness, weigh, bevel=bevel)


def along(points, s):
    """Point at fraction s (0 to 1) of a polyline's index range, with its forward tangent."""
    scaled = s * (len(points) - 1)
    i = min(int(scaled), len(points) - 2)
    t = scaled - i
    return kc.lerp(points[i], points[i + 1], t), unit(sub(points[i + 1], points[i]))


