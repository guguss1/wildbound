"""Generate the six Caramelo critter clip data modules from their Blender clip JSON.

No system Python on the main machine: run it inside Blender's bundled Python, from the repo root:
  & "C:\\Program Files\\Blender Foundation\\Blender 5.0\\blender.exe" --background --python tools/generate_candy_critter_clips.py
It also runs with any plain Python 3:  python -I -B tools/generate_candy_critter_clips.py

Input:  assets/blender/caramelo/<slug>/<file>-clips.json
        { Clip: { length, loop, priority, easing?, keys: [ { t, pose: { Bone: [dx,dy,dz,rx,ry,rz] } } ] } }
Output: src/wildbound/WildboundCandyCritterClips<Name>.luau, each
        return require(script.Parent:WaitForChild("WildboundCandyClipKit")).define({ ORDER = {...}, CLIPS = {...} })
ORDER keeps the JSON order (a Luau table loses it). Numbers are rounded to 4 decimals. Prints one line per module with
its byte length and Adler-32 (LF line endings, no trailing newline, the same fingerprint the Studio check uses).
"""
import json
import os
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CARAMELO = os.path.join(REPO, "assets", "blender", "caramelo")
OUT = os.path.join(REPO, "src", "wildbound")

SETS = [
    ("DuquesaBurbuja", "duquesa-burbuja", "duquesa-burbuja-v2-clips.json"),
    ("Mochimiau", "mochimiau", "mochimiau-clips.json"),
    ("Canelin", "canelin", "canelin-clips.json"),
    ("Flanin", "flanin", "flanin-clips.json"),
    ("Mielita", "mielita", "mielita-clips.json"),
    ("GatoRepartidor", "gato-repartidor", "gato-repartidor-clips.json"),
]

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
PRIORITIES = {"Idle", "Movement", "Action"}


def num(value):
    r = round(float(value), 4)
    if r == 0:
        return "0"
    if r == int(r):
        return str(int(r))
    text = "%.4f" % r
    return text.rstrip("0").rstrip(".")


def key(name):
    return name if IDENT.match(name) else '["%s"]' % name.replace('"', '\\"')


def string(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def clip_source(clip):
    assert clip["priority"] in PRIORITIES, clip["priority"]
    lines = ["{ length = %s, loop = %s, priority = %s," % (
        num(clip["length"]), "true" if clip["loop"] else "false", string(clip["priority"]))]
    if clip.get("easing"):
        assert clip["easing"] == "Linear", clip["easing"]
        lines[0] += ' easing = "Linear",'
    lines.append("\t\tkeys = {")
    for item in clip["keys"]:
        bones = []
        for bone, values in item["pose"].items():
            assert len(values) == 6, (bone, values)
            bones.append("%s = { %s }" % (key(bone), ", ".join(num(v) for v in values)))
        pose = "{ %s }" % ", ".join(bones) if bones else "{}"
        lines.append("\t\t\t{ t = %s, pose = %s }," % (num(item["t"]), pose))
    lines.append("\t\t} }")
    return "\n".join(lines)


def module_source(name, rel, data):
    out = [
        "-- GENERATED by tools/generate_candy_critter_clips.py from %s; do not edit by hand." % rel,
        "-- %s's clips for WildboundCandyClipKit (odd/tasks/wildbound-candy-critters.md): per key, an offset in studs and a" % name,
        "-- rotation in degrees per bone, in model axes (X right, Y up, -Z forward), relative to rest.",
        'return require(script.Parent:WaitForChild("WildboundCandyClipKit")).define({',
        "\tORDER = { %s }," % ", ".join(string(c) for c in data.keys()),
        "\tCLIPS = {",
    ]
    for clip_name, clip in data.items():
        out.append("\t\t%s = %s," % (key(clip_name), clip_source(clip)))
    out.append("\t},")
    out.append("})")
    return "\n".join(out)


def main():
    for name, slug, filename in SETS:
        path = os.path.join(CARAMELO, slug, filename)
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
        rel = "assets/blender/caramelo/%s/%s" % (slug, filename)
        text = module_source(name, rel, data)
        target = os.path.join(OUT, "WildboundCandyCritterClips%s.luau" % name)
        with open(target, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text + "\n")
        body = text.encode("utf-8")
        keys = sum(len(c["keys"]) for c in data.values())
        print("CRITTER_CLIPS %s clips=%d keys=%d bytes=%d adler32=%d" % (
            name, len(data), keys, len(body), zlib.adler32(body) & 0xFFFFFFFF))
    sys.stdout.flush()


main()
