"""Emit the Studio ModuleScript source for the relief plan (task R2).

The plan JSON stays the single source of truth. This tool only reformats it, as export_forest_layout_luau.py does:

    python -I -B tools/export_relief_luau.py            # writes the module to stdout
    python -I -B tools/export_relief_luau.py --adler32  # prints the module's Adler-32

Paste the output into `ServerStorage.WildboundReliefLayout` and compare the Adler-32 with the one computed over the
script's Source in Studio, so a transcription slip cannot go unnoticed.
"""
import argparse
import json
import sys
import zlib
from pathlib import Path

PLAN = Path(__file__).resolve().parent.parent / "assets" / "maps" / "forest-layout" / "relief-v1.json"
NUMBER_FIELDS = ("height", "crestWidth", "slopeDeg")


def _segment_row(seg):
    values = [seg["id"], seg["feature"], seg["a"][0], seg["a"][1], seg["b"][0], seg["b"][1]]
    values += [seg[key] for key in NUMBER_FIELDS]
    return "S|" + "|".join(str(v) for v in values)


def render(plan: dict) -> str:
    rows = [_segment_row(seg) for seg in plan["segments"]]
    rows += ["P|" + "|".join(str(s[k]) for k in ("x", "z", "y")) for s in plan["samples"]]
    rows += ["T|" + tree for tree in plan["removedTrees"]]
    text = "\n".join(rows)
    if "]==]" in text:
        raise ValueError("plan text would close the Luau long string")
    return f"""-- GENERATED by tools/export_relief_luau.py from {PLAN.name}. Do not edit by hand.
-- Returns {{ floorTop, partsPerSegment, segments = {{ id, feature, ax, az, bx, bz, height, crestWidth, slopeDeg }},
-- samples = {{ x, z, y }}, removedTrees = {{ id }} }}. Read by ServerScriptService.WildboundRelief (the height rule),
-- the map builder's buildRelief and the forest dressing.
local ROWS = [==[
{text}
]==]

local layout = {{ floorTop = {plan["floorTop"]}, partsPerSegment = {plan["partsPerSegment"]}, segments = {{}}, samples = {{}},
    removedTrees = {{}} }}
for line in string.gmatch(ROWS, '[^\\n]+') do
    local kind, rest = string.match(line, '^(%a)|(.*)$')
    local fields = string.split(rest, '|')
    if kind == 'S' then
        table.insert(layout.segments, {{ id = fields[1], feature = fields[2], ax = tonumber(fields[3]),
            az = tonumber(fields[4]), bx = tonumber(fields[5]), bz = tonumber(fields[6]), height = tonumber(fields[7]),
            crestWidth = tonumber(fields[8]), slopeDeg = tonumber(fields[9]) }})
    elseif kind == 'P' then
        table.insert(layout.samples, {{ x = tonumber(fields[1]), z = tonumber(fields[2]), y = tonumber(fields[3]) }})
    elseif kind == 'T' then
        table.insert(layout.removedTrees, fields[1])
    else
        error('malformed relief row: ' .. line)
    end
end
return layout
"""


def adler32(text: str) -> int:
    return zlib.adler32(text.encode("utf-8")) & 0xFFFFFFFF


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--adler32", action="store_true", help="print only the Adler-32 of the module")
    args = parser.parse_args(argv)
    module = render(json.loads(PLAN.read_text(encoding="utf-8")))
    if args.adler32:
        print(adler32(module))
    else:
        sys.stdout.buffer.write(module.encode("utf-8"))  # bytes: keep LF on Windows
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
