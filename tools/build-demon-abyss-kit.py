def raw_size(build, seed):
    """Measured bounding box of a prop before fitting. Chunks and thorns that stand just past the table's size
    (inside its 10% tolerance) would otherwise be squeezed into it, bending the walk top and the gateway."""
    probe = kc.Asset("probe", seed=seed)
    build(probe)
    low, high = probe.bbox()
    return tuple(h - l for l, h in zip(low, high))


def brighter_studio():
    """Near-black palettes vanish in the shared studio light. Preview renders only: more key, fill and sky."""
    if bk.bpy is None:
        return
    shared = kc.add_studio

    def studio(scene, prefix="SP"):
        camera = shared(scene, prefix)
        bk.bpy.data.lights[f"{prefix}_Key"].energy = 3.6
        bk.bpy.data.lights[f"{prefix}_Fill"].energy = 1.4
        scene.world.node_tree.nodes["Background"].inputs[1].default_value = 1.3
        return camera

    kc.add_studio = studio


