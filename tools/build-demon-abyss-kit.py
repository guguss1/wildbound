def edge_at(part, z, side):
    """Nearest |x| of the part's section at height z on one side of the gateway."""
    cuts = []
    for tri in bk.triangulate(part):
        pts = [part.vertices[i] for i in tri]
        for p, q in ((pts[0], pts[1]), (pts[1], pts[2]), (pts[2], pts[0])):
            if (p[2] - z) * (q[2] - z) < 0:
                x = p[0] + (z - p[2]) / (q[2] - p[2]) * (q[0] - p[0])
                if x * side > 6.0:
                    cuts.append(abs(x))
    return min(cuts)


def build_rift_gate(a):
    """Two crooked piers of stacked slabs, one leaning away and one leaning in, a broken lintel with teeth and
    thorns, glowing seams down the inner edges (outside the corridor) and under the lintel."""
    rng = a.rng
    stone, glow = a.part("Stone"), a.part("Neon_Rift")
    for side, shift, top, blocks in ((-1, 0.3, 10.8, 5), (1, -0.2, 10.2, 5)):  # one pier leans away, one leans in
        step = top / blocks
        for i in range(blocks):
            inner = 8.4 + shift * i
            width = 5.0 - 0.1 * i
            block(stone, rng, side * (inner + width / 2) + rng.uniform(-0.05, 0.05), rng.uniform(-0.12, 0.12),
                  step * i - (0.03 if i else 0.0), step * (i + 1), width, 6.2 - 0.25 * i, taper=0.92,
                  jitter=0.16, yaw=0.06 * (-1) ** (i + (side > 0)))
        for k in range(2):
            block(stone, rng, side * 13.0, rng.uniform(-0.6, 0.6), 0.0, 4.2 - 1.6 * k, 1.5, 3.0,
                  taper=0.7, jitter=0.15, yaw=rng.uniform(-0.2, 0.2))
    block(stone, rng, -6.7, 0.1, 11.4, 13.6, 14.2, 5.6, taper=0.92, jitter=0.3, yaw=0.04)
    block(stone, rng, 6.7, -0.1, 11.3, 13.3, 12.8, 5.6, taper=0.92, jitter=0.3, yaw=-0.05)
    block(stone, rng, -4.0, 0.0, 13.6, 14.8, 5.0, 3.6, taper=0.7, jitter=0.2, yaw=0.3)
    block(stone, rng, 7.0, 0.2, 13.3, 14.4, 4.4, 3.4, taper=0.7, jitter=0.2, yaw=-0.2)
    for x, y, z, top in ((-11.0, -0.8, 13.4, 17.8), (-6.0, 1.0, 13.7, 16.2), (-1.5, -1.2, 14.6, 17.0),
                         (3.5, 0.6, 14.4, 16.6), (8.0, -0.8, 14.2, 18.0), (11.6, 0.8, 13.3, 16.0)):
        org.rough_tube(stone, rng, [(x, y, z), (x + rng.uniform(-0.8, 0.8), y, top)], [0.9, 0.0], 4, rough=0.1)
    for x, y in ((-3.5, 0.4), (1.5, -0.5), (4.2, 0.6)):
        org.rough_tube(stone, rng, [(x, y, 12.0), (x + 0.1, y, 11.1)], [0.8, 0.0], 4, rough=0.08)
    for x, y, w, d, h in ((-11.4, -3.2, 1.2, 1.1, 0.8), (11.4, 3.1, 1.2, 1.1, 0.7)):
        block(stone, rng, x, y, 0.0, h, w, d, taper=0.8, jitter=0.1, yaw=rng.uniform(0.0, 1.0))
    for side in (-1, 1):
        points = [(side * (edge_at(stone, z, side) - 0.05), 0.0, z) for z in (1.2, 3.6, 6.4, 9.2)]
        top = [[(x, -0.5, z), (x, 0.5, z)] for x, _, z in points]
        low = [[(x + side * 0.45, -0.5, z), (x + side * 0.45, 0.5, z)] for x, _, z in points]
        org.slab_between(glow, top, low)
    top = [[(x, -0.5, 11.25), (x, 0.5, 11.25)] for x in (-6.0, -2.0, 2.0, 6.0)]
    low = [[(x, -0.5, 11.6), (x, 0.5, 11.6)] for x in (-6.0, -2.0, 2.0, 6.0)]
    org.slab_between(glow, top, low)
    for x, y, tilt, height in ((-9.6, 0.4, (-0.2, 0.0), 3.4), (9.0, -0.3, (0.25, 0.1), 2.8)):
        org.shard(glow, rng, (x, y, 13.0), (tilt[0], tilt[1], 1.0), 0.8, height, sides=4, belly=1.2, stages=2)


