def block(part, rng, x, y, z0, z1, width, depth, taper=0.95, jitter=0.16, yaw=0.0):
    org.jittered_block(part, rng, (x, y, (z0 + z1) / 2), (width, depth, z1 - z0), jitter=jitter, taper=taper,
                       yaw=yaw + rng.uniform(-0.05, 0.05))


def inscribed_walk_box(part_vertices, box_top, name="walk"):
    """A square walk box inside the flat top of a slab that fans to a centre vertex at surface_z, measured on
    the fitted vertices (fitting shifts the prop a little, so the centre is not at the origin)."""
    surface_z = max(v[2] for v in part_vertices)  # the flat top, wherever fitting left it
    top = [v for v in part_vertices if v[2] > surface_z - 0.01]
    mean = (sum(v[0] for v in top) / len(top), sum(v[1] for v in top) / len(top))
    centre = min(top, key=lambda v: math.dist(v[:2], mean))
    ring = [v for v in top if v is not centre]
    ring.sort(key=lambda v: math.atan2(v[1] - centre[1], v[0] - centre[0]))
    half = round(inscribed_square_half([(v[0], v[1]) for v in ring], (centre[0], centre[1])) * 0.97, 3)
    return {"name": name, "center": [round(centre[0], 4), round(centre[1], 4), round(box_top / 2, 4)],
            "size": [2 * half, 2 * half, box_top], "pitch_deg": 0.0}


def ribbon(part, points, half, top_z, low_z):
    """A flat glowing strip along a polyline in plan view, from low_z up to top_z."""
    top, low = [], []
    for i, (x, y) in enumerate(points):
        ahead, behind = points[min(i + 1, len(points) - 1)], points[max(i - 1, 0)]
        dx, dy = ahead[0] - behind[0], ahead[1] - behind[1]
        size = math.hypot(dx, dy)
        nx, ny = -dy / size, dx / size
        top.append([(x + nx * half, y + ny * half, top_z), (x - nx * half, y - ny * half, top_z)])
        low.append([(x + nx * half, y + ny * half, low_z), (x - nx * half, y - ny * half, low_z)])
    org.slab_between(part, top, low)


def box_record(name, centre, size):
    return {"name": name, "center": [round(c, 4) for c in centre], "size": [round(s, 4) for s in size]}


