def build_calm_stone(a):
    """A smooth, pale standing stone: a leaning, flat-topped seven-sided block with chamfered shoulders, a cool
    glowing band across its front and a pebble."""
    rng = a.rng
    stone, rune = a.part("Stone"), a.part("Neon_Rune")
    rings = [org.irregular_ring((0.05 * z, -0.015 * z, z), U, V, radius, radius, 7, rng, wobble=0.035,
                                jitter=0.012, phase=math.pi)
             for z, radius in ((0.0, 2.75), (1.8, 2.8), (3.6, 2.45), (5.2, 1.9), (6.0, 1.45))]
