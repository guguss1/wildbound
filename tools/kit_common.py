def ring_points(center, u, v, radius_u, radius_v, sides, phase=0.0):
    return [add(center, add(mul(u, math.cos(phase + TAU * k / sides) * radius_u),
                            mul(v, math.sin(phase + TAU * k / sides) * radius_v)))
            for k in range(sides)]


def loft(part, rings, weigh, start="cap", end="cap"):
    """Close a stack of same-sized rings. A cap is an n-gon; a tuple end is a fan to a tip."""
    sides = len(rings[0])
    vertices = [v for ring in rings for v in ring]
    faces = []
    for row in range(len(rings) - 1):
        for i in range(sides):
            j = (i + 1) % sides
            a, b = row * sides + i, row * sides + j
            faces.append((a, b, b + sides, a + sides))
    if isinstance(start, tuple):
        index = len(vertices)
        vertices.append(start)
        faces.extend((index, (i + 1) % sides, i) for i in range(sides))
    else:
        faces.append(tuple(reversed(range(sides))))
    last = (len(rings) - 1) * sides
    if isinstance(end, tuple):
        index = len(vertices)
        vertices.append(end)
        faces.extend((last + i, last + (i + 1) % sides, index) for i in range(sides))
    else:
        faces.append(tuple(last + i for i in range(sides)))
    part.add(vertices, faces, weigh)


def loft_closed(part, rings, weigh):
    """A ring of rings, joined end to start. No caps, so it is a closed torus shape."""
    sides, count = len(rings[0]), len(rings)
    vertices = [v for ring in rings for v in ring]
    faces = []
    for row in range(count):
        nxt = (row + 1) % count
        for i in range(sides):
            j = (i + 1) % sides
            faces.append((row * sides + i, row * sides + j, nxt * sides + j, nxt * sides + i))
    part.add(vertices, faces, weigh)


def arc_profile(radius, height, steps, bottom=-90.0, top=90.0, base_z=0.0):
    """(r, h) points along an ellipse arc; 0 degrees is the equator, +-90 are the poles."""
    points = []
    for i in range(steps + 1):
        a = math.radians(bottom + (top - bottom) * i / steps)
        r = radius * math.cos(a)
        points.append((0.0 if r < 1e-9 else r, base_z + height * math.sin(a)))
    return points


def lathe(part, profile, sides, weigh, center=(0.0, 0.0, 0.0), frame=Z_UP, scale=(1.0, 1.0),
          phase=0.0, twist=0.0, jitter=0.0, rng=None):
    """Turn (radius, height) points around an axis. A radius of 0 at either end is a tip.

    frame is (u, v, w): w is the axis. scale stretches the cross-section along u and v.
    twist adds an angle per ring, which turns flat bands into faceted spirals.
    """
    u, v, w = frame
    rings, start, end = [], "cap", "cap"
    for index, (radius, height) in enumerate(profile):
        origin = madd(center, w, height)
        if radius <= 0.0:
            if index == 0:
                start = origin
            else:
                assert index == len(profile) - 1, "a tip can only be the first or last point"
                end = origin
            continue
        ring = []
        for k in range(sides):
            amount = radius * (1.0 + jitter * rng.uniform(-1.0, 1.0)) if jitter else radius
            angle = phase + twist * len(rings) + TAU * k / sides
            ring.append(add(origin, add(mul(u, math.cos(angle) * amount * scale[0]),
                                        mul(v, math.sin(angle) * amount * scale[1]))))
        rings.append(ring)
    loft(part, rings, weigh, start, end)


def path_frames(points, reference=None):
    """Parallel-transport frames along a path, so twist comes only from the caller."""
    tangent = unit(sub(points[1], points[0]))
    if reference is None:
        reference = (0.0, 0.0, 1.0) if abs(tangent[2]) < 0.85 else (1.0, 0.0, 0.0)
    side = unit(cross(reference, tangent))
    frames = []
    for index in range(len(points)):
        tangent = unit(sub(points[min(index + 1, len(points) - 1)], points[max(index - 1, 0)]))
        side = unit(sub(side, mul(tangent, dot(side, tangent))))
        frames.append((side, cross(tangent, side), tangent))
    return frames


def tube(part, points, radii, sides, weigh, phase=0.0, squash=1.0, reference=None):
    """Faceted limb along a path. A radius of 0 at an end makes a sharp tip."""
    frames = path_frames(points, reference)
    rings, start, end = [], "cap", "cap"
    for index, (point, radius) in enumerate(zip(points, radii)):
        if radius <= 0.0:
            if index == 0:
                start = point
            else:
                end = point
            continue
        side, normal, _ = frames[index]
        rings.append([add(point, add(mul(side, math.cos(phase + TAU * k / sides) * radius * squash),
                                     mul(normal, math.sin(phase + TAU * k / sides) * radius)))
                      for k in range(sides)])
    loft(part, rings, weigh, start, end)


def hexahedron(part, corners, weigh):
    """Six-sided block from eight corners: bottom four, then top four."""
    part.add(corners, [(3, 2, 1, 0), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)],
             weigh)


def box(part, center, size, weigh, yaw=0.0, taper=1.0):
    """Axis-aligned block, optionally turned about Z; taper < 1 narrows the top face."""
    sx, sy, sz = (s / 2 for s in size)
    cos_y, sin_y = math.cos(yaw), math.sin(yaw)

    def place(x, y, z):
        return (center[0] + x * cos_y - y * sin_y, center[1] + x * sin_y + y * cos_y, center[2] + z)

    ring = [(-sx, -sy), (sx, -sy), (sx, sy), (-sx, sy)]
    hexahedron(part, [place(x, y, -sz) for x, y in ring] + [place(x * taper, y * taper, sz) for x, y in ring],
               weigh)


def slab(part, outline, origin, u, v, normal, thickness, weigh, bevel=0.0):
    """Extrude a flat outline (list of (a, b) in the u, v plane) along the normal.

    With bevel > 0 the top face is inset, which chamfers the rim so it catches light.
    """
    cx = sum(a for a, _ in outline) / len(outline)
    cy = sum(b for _, b in outline) / len(outline)

    def ring(scale, offset):
        return [add(add(madd(origin, normal, offset), mul(u, cx + (a - cx) * scale)),
                    mul(v, cy + (b - cy) * scale)) for a, b in outline]

    if bevel > 0.0:
        rings = [ring(1.0, 0.0), ring(1.0, thickness * 0.55), ring(1.0 - bevel, thickness)]
    else:
        rings = [ring(1.0, 0.0), ring(1.0, thickness)]
    loft(part, rings, weigh)


def torus(part, center, u, v, major, minor, segments, sides, weigh, phase=0.0, squash=1.0):
    """A ring in the u, v plane: major radius to the tube centre, minor radius of the tube."""
    normal = cross(u, v)
    rings = []
    for i in range(segments):
        a = TAU * i / segments
        radial = add(mul(u, math.cos(a)), mul(v, math.sin(a)))
        spot = madd(center, radial, major)
        rings.append([add(madd(spot, radial, math.cos(phase + TAU * k / sides) * minor),
                          mul(normal, math.sin(phase + TAU * k / sides) * minor * squash))
                      for k in range(sides)])
    loft_closed(part, rings, weigh)


def crystal(part, base, direction, radius, height, weigh, sides=6, tip=0.0):
    """Hexagonal crystal: a short prism that ends in a point (or a small flat top if tip > 0)."""
    u, v, w = basis(direction)
    lower = ring_points(base, u, v, radius, radius, sides)
    shoulder = ring_points(madd(base, w, height * 0.6), u, v, radius * 0.9, radius * 0.9, sides, 0.2)
    if tip > 0.0:
        top = ring_points(madd(base, w, height), u, v, tip, tip, sides, 0.2)
        loft(part, [lower, shoulder, top], weigh)
    else:
        loft(part, [lower, shoulder], weigh, end=madd(base, w, height))


