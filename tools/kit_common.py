class Part:
    """One mesh object, one material."""

    def __init__(self, label):
        self.label = label
        self.vertices, self.faces, self.weights = [], [], []

    def add(self, vertices, faces, weigh):
        start = len(self.vertices)
        for vertex in vertices:
            self.vertices.append(tuple(vertex))
            self.weights.append(weigh(tuple(vertex)))
        self.faces.extend(tuple(start + i for i in face) for face in faces)

    @property
    def triangles(self):
        return sum(len(face) - 2 for face in self.faces)


class Asset:
    def __init__(self, name, seed=1):
        self.name = name
        self.parts = OrderedDict()
        self.bones = []  # (name, parent, head, tail)
        self.rng = random.Random(seed)
        self.hidden_by_default = set()
        self.fit = (1.0, 1.0, 1.0)

    def part(self, label):
        if label not in self.parts:
            self.parts[label] = Part(label)
        return self.parts[label]

    def bone(self, name, parent, head, tail):
        self.bones.append((name, parent, tuple(head), tuple(tail)))

    @property
    def triangles(self):
        return sum(part.triangles for part in self.parts.values())

    def bbox(self):
        points = [v for part in self.parts.values() for v in part.vertices]
        return ([min(p[i] for p in points) for i in range(3)],
                [max(p[i] for p in points) for i in range(3)])


def fit_asset(asset, size, band_fraction=0.1):
    """Scale each axis to the spec size, drop the lowest point onto Z 0 and centre the base.

    Bones get the same transform, so the rig stays inside the skin. The scale factors are
    kept on the asset so a report shows how far the raw design was from the spec.
    """
    low, high = asset.bbox()
    scale = tuple(size[i] / (high[i] - low[i]) for i in range(3))

    def scaled(v):
        return tuple((v[i] - low[i]) * scale[i] for i in range(3))

    for part in asset.parts.values():
        part.vertices = [scaled(v) for v in part.vertices]
    points = [v for part in asset.parts.values() for v in part.vertices]
    band = max(p[2] for p in points) * band_fraction
    base = [p for p in points if p[2] <= band]
    shift = tuple(-(min(p[i] for p in base) + max(p[i] for p in base)) / 2 for i in (0, 1))

    def placed(v):
        s = scaled(v)
        return (s[0] + shift[0], s[1] + shift[1], s[2])

    for part in asset.parts.values():
        part.vertices = [(v[0] + shift[0], v[1] + shift[1], v[2]) for v in part.vertices]
    asset.bones = [(n, p, placed(h), placed(t)) for n, p, h, t in asset.bones]
    asset.fit = scale
    return scale


