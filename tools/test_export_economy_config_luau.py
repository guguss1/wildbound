"""Contracts for the generated Luau economy tuning module (M5.2, wave W7).

Studio cannot read the document's ```json economy-tuning block, so the game reads a generated
Luau copy, `src/wildbound/WildboundEconomyConfig.luau`. These tests fail when that copy and the
document diverge, and parse the Luau back to prove the copy is faithful, not just stable.

    python -I -B -m unittest discover -s tools -p "test_export_economy_config_luau.py"
"""

import copy
import io
import re
import unittest
from contextlib import redirect_stdout
from pathlib import Path

import export_economy_config_luau as gen
import simulate_economy as eco

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / "docs/mechanics/wildbound-economy-p0.md"
MODULE = REPO / "src/wildbound/WildboundEconomyConfig.luau"


def tuning():
    return eco.load_tuning(DOC)


def game_data(data):
    data = copy.deepcopy(data)
    data.pop("simulatorInputs", None)
    return data


def without_empty_dicts(value):
    """Luau has one table type, so an empty JSON object reads back as an empty list."""
    if isinstance(value, dict):
        return {k: without_empty_dicts(v) for k, v in value.items()} if value else []
    if isinstance(value, list):
        return [without_empty_dicts(v) for v in value]
    return value


class CommittedModuleTests(unittest.TestCase):
    def test_committed_module_matches_the_document(self):
        expected = gen.render(tuning())
        actual = MODULE.read_text(encoding="utf-8").replace("\r\n", "\n")
        self.assertEqual(actual, expected, "WildboundEconomyConfig.luau differs from the document; run --write")

    def test_committed_module_parses_back_to_the_document_json(self):
        parsed = gen.parse_luau(MODULE.read_text(encoding="utf-8"))
        self.assertEqual(parsed, without_empty_dicts(game_data(tuning())))

    def test_check_flag_passes_on_the_committed_module(self):
        with redirect_stdout(io.StringIO()):
            self.assertEqual(gen.main(["--check"]), 0)


class RenderTests(unittest.TestCase):
    def test_a_changed_number_changes_the_module(self):
        data = tuning()
        base = gen.render(data)
        data["loss"]["rateBasisPoints"] = 4999
        self.assertNotEqual(gen.render(data), base)
        self.assertEqual(gen.parse_luau(gen.render(data))["loss"]["rateBasisPoints"], 4999)

    def test_check_flag_fails_when_the_module_diverges(self):
        data = tuning()
        data["recipes"]["seal"]["cost"]["fogbark"] = 9
        with redirect_stdout(io.StringIO()):
            self.assertEqual(gen.check(gen.render(data)), 1)

    def test_simulator_inputs_are_left_out(self):
        text = gen.render(tuning())
        self.assertNotIn("simulatorInputs", text)
        self.assertNotIn("archetypes", text)

    def test_render_is_deterministic_and_frozen(self):
        data = tuning()
        self.assertEqual(gen.render(data), gen.render(copy.deepcopy(data)))
        text = gen.render(data)
        self.assertIn("table.freeze", text)
        self.assertTrue(text.startswith("-- GENERATED by tools/export_economy_config_luau.py"))

    def test_keys_that_are_not_identifiers_are_bracketed(self):
        text = gen.render({"schema": "x", "levelEffects": {"2": {"a": True}}, "end": 1})
        self.assertIn('["2"] = {', text)
        self.assertIn('["end"] = 1', text)
        self.assertEqual(gen.parse_luau(text), {"schema": "x", "levelEffects": {"2": {"a": True}}, "end": 1})

    def test_strings_are_escaped_and_floats_keep_their_value(self):
        data = {"a": 'say "hi" \\ there', "b": 0.4, "c": 4.0, "d": [1, 2], "e": False}
        self.assertEqual(gen.parse_luau(gen.render(data)), data)

    def test_unsupported_values_are_refused(self):
        for bad in ({"a": None}, {"a": "café"}, {"a": float("nan")}, {"a": "x\ny"}):
            with self.assertRaises(ValueError):
                gen.render(bad)

    def test_monetization_none_is_carried(self):
        self.assertEqual(gen.parse_luau(gen.render(tuning()))["monetization"], "none")
        self.assertRegex(gen.render(tuning()), re.compile(r'^\tmonetization = "none",$', re.M))


if __name__ == "__main__":
    unittest.main()
